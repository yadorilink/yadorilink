#!/usr/bin/env python3
"""Render the Homebrew formula for one release from its release ledger.

The formula installs the engine bundles (macOS arm64, Linux x86_64) that the
release already published and the signed channel manifest already lists, so
Homebrew pins the same bytes as every other channel: each URL and sha256 comes
straight from `.github/channels/releases/<version>.json`, and nothing is
downloaded or rebuilt here. Run it with the ledger path and the version:

    python3 packaging/homebrew/render-formula.py \
        .github/channels/releases/0.1.0-beta.9.json 0.1.0-beta.9 > yadorilink.rb

`--self-test` checks the renderer against a built-in ledger.
"""
import json
import re
import sys
from pathlib import Path

TARGETS = {"macos-aarch64": ("on_macos", "on_arm"), "linux-x86_64": ("on_linux", "on_intel")}
VERSION = re.compile(r"^[0-9]+\.[0-9]+\.[0-9]+(-[0-9A-Za-z.]+)?$")
SHA256 = re.compile(r"^[0-9a-f]{64}$")
# Only plain file-name characters: the URL is placed in a Ruby string, where `#{...}` would run code.
URL = re.compile(r"^https://github\.com/yadorilink/yadorilink/releases/download/v[A-Za-z0-9._+-]+/[A-Za-z0-9._+-]+\.zip$")

HEADER = '''# Generated by packaging/homebrew/render-formula.py from the release ledger; do not edit.
class Yadorilink < Formula
  desc "Peer-to-peer file sync: the yadorilink command line and daemon"
  homepage "https://yadori.link"
  version "{version}"
  license :cannot_represent

'''

BLOCKS = '''  {os_block} do
    {arch_block} do
      url "{url}"
      sha256 "{sha256}"

      def install
        {install}
      end
    end
  end

'''

# The marker is how the daemon learns Homebrew owns it (install_source.rs): it reads
# <prefix>/share/yadorilink/install-source beside the real program and then refuses
# self-update and uninstall with the brew commands.
MARKER = '\n        (share/"yadorilink").mkpath\n        (share/"yadorilink/install-source").write "homebrew\\n"'
INSTALL = {
    "macos-aarch64": 'bin.install "bin/yadorilink", "bin/yadorilink-daemon"' + MARKER,
    "linux-x86_64": 'bin.install "yadorilink", "yadorilink-daemon"' + MARKER,
}

FOOTER = '''  def caveats
    <<~EOS
      Start the daemon, then sign in (this also adds the computer to your account):
        yadorilink daemon start
        yadorilink login
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/yadorilink --version")
    assert_match version.to_s, shell_output("#{bin}/yadorilink-daemon --version")
  end
end
'''


def render(ledger: dict, version: str) -> str:
    if not VERSION.match(version):
        raise SystemExit(f"error: not a version: {version!r}")
    script = ledger.get("script")
    if not isinstance(script, dict):
        raise SystemExit("error: the ledger has no `script` entry")
    out = [HEADER.format(version=version)]
    for target, (os_block, arch_block) in TARGETS.items():
        entry = script.get(target)
        if not isinstance(entry, dict):
            raise SystemExit(f"error: the ledger has no engine bundle for {target}")
        url, sha = entry.get("github_url"), entry.get("sha256")
        if not isinstance(url, str) or not URL.match(url) or f"/v{version}/" not in url:
            raise SystemExit(f"error: {target}: github_url is not this release's asset: {url!r}")
        if not isinstance(sha, str) or not SHA256.match(sha):
            raise SystemExit(f"error: {target}: sha256 is not a lowercase hex digest")
        out.append(BLOCKS.format(os_block=os_block, arch_block=arch_block, url=url,
                                 sha256=sha, install=INSTALL[target]))
    out.append(FOOTER)
    return "".join(out)


def self_test() -> None:
    sha = "ab" * 32
    base = "https://github.com/yadorilink/yadorilink/releases/download/v1.2.3-beta.4/"
    ledger = {"script": {t: {"github_url": f"{base}yadorilink-engine-beta-{t}.zip", "sha256": sha}
                         for t in TARGETS}}
    text = render(ledger, "1.2.3-beta.4")
    assert text.count(f'sha256 "{sha}"') == 2 and 'version "1.2.3-beta.4"' in text
    assert "def caveats" in text and "yadorilink login" in text
    assert "on_arm do" in text and "on_intel do" in text and "bin/yadorilink-daemon" in text
    for mutate, why in [
        (lambda d: d["script"].pop("linux-x86_64"), "missing target"),
        (lambda d: d["script"]["linux-x86_64"].update(sha256="AB" * 32), "bad sha"),
        (lambda d: d["script"]["linux-x86_64"].update(github_url=base.replace("v1.2.3", "v9.9.9") + "x.zip"), "other release"),
        (lambda d: d["script"]["linux-x86_64"].update(github_url="http://evil.example/x.zip"), "foreign url"),
        (lambda d: d["script"]["linux-x86_64"].update(github_url=base + "#{system(%q(id))}.zip"), "ruby interpolation"),
    ]:
        bad = json.loads(json.dumps(ledger))
        mutate(bad)
        try:
            render(bad, "1.2.3-beta.4")
        except SystemExit:
            continue
        raise AssertionError(f"accepted a bad ledger: {why}")
    print("render-formula self-test ok")


def main(argv: list) -> int:
    if argv == ["--self-test"]:
        self_test()
        return 0
    if len(argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    ledger = json.loads(Path(argv[0]).read_text(encoding="utf-8"))
    sys.stdout.write(render(ledger, argv[1]))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
