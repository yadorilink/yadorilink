# str_lt A B: true when A sorts before B (fixed-width timestamps compare as text).
str_lt() { [ "$1" != "$2" ] && [ "$(printf '%s\n%s\n' "$1" "$2" | LC_ALL=C sort | head -n 1)" = "$1" ]; }

# list_has "a b c" X: true when X is one of the words.
list_has() { for w in $1; do [ "$w" = "$2" ] && return 0; done; return 1; }

# fetch_envelope URL OUT: download a signed envelope. Returns 0 (HTTP 200), 1 (404),
# 2 (another HTTP status, in $HTTP_CODE) or 3 (the network failed).
fetch_envelope() {
    HTTP_CODE=$(curl -sSL --max-redirs 5 --proto "$CURL_PROTO" --proto-redir "$CURL_PROTO" --tlsv1.2 --connect-timeout 15 --max-time 60 \
        --max-filesize 1048576 -o "$2" -w '%{http_code}' "$1") || return 3
    case $HTTP_CODE in 200) return 0 ;; 404) return 1 ;; *) return 2 ;; esac
}

# verify_envelope ENVFILE BODYFILE: check the key id and the Ed25519 signature against the
# pinned trust set and write the signed body to BODYFILE, or refuse (4). A key that is not pinned
# is status $UNPINNED_STATUS: 22 only while the LIVE channel manifest is being checked ("this
# installer is too far behind the keys now in use"); any other manifest is a plain refusal (4).
UNPINNED_STATUS=4
verify_envelope() {
    env_key=$(envelope_field "$1" key_id) || refuse 4 "update manifest is malformed (key_id)"
    KEY_HEX=""
    for pair in $TRUST_SET; do
        [ "${pair%%:*}" = "$env_key" ] && KEY_HEX=${pair#*:}
    done
    [ -n "$KEY_HEX" ] || refuse "$UNPINNED_STATUS" "update manifest is signed with key '$env_key', which is not one of the pinned release keys. Nothing was installed.$( [ "$UNPINNED_STATUS" != 22 ] || printf ' This installer is older than the keys now in use: run the one-line installer again (curl -fsSL https://yadori.link/install.sh | sh) to get one that pins them.')"
    envelope_field "$1" manifest_json > "$2" || refuse 4 "update manifest is malformed (manifest_json)"
    sig_b64=$(envelope_field "$1" signature_base64) || refuse 4 "update manifest is malformed (signature_base64)"
    b64_to_file "$sig_b64" "$WORK/manifest.sig" || refuse 4 "update manifest signature is not valid base64"
    [ "$(file_size "$WORK/manifest.sig")" = 64 ] || refuse 4 "update manifest signature has the wrong length"
    [ -n "$VERIFIER" ] || fetch_verifier
    if ! ed25519_check "$KEY_HEX" "$2" "$WORK/manifest.sig"; then
        refuse 4 "the update manifest signature does NOT verify against the pinned release key. Refusing. Nothing was installed."
    fi
    ENV_KEY=$env_key
}

# read_manifest BODYFILE [lenient]: parse a verified body into the M_* variables for this
# channel, platform and architecture.
read_manifest() {
    sel=$(select_entry "$1" "$CHANNEL" "$PLATFORM" "$ARCH" "${2:-}") || die "cannot read the update manifest"
    case $sel in
        OK*) ;;
        *) refuse 4 "update manifest: ${sel#ERR } for $CHANNEL/$TARGET. Nothing was installed." ;;
    esac
    M_VERSION=""; M_KILL=""; M_URL=""; M_SHA=""; M_SIZE=""; M_NOTES=""; M_MIN=""; M_GEN=""; M_EXPIRES=""; M_WITHDRAWN=""
    while IFS='=' read -r k v; do
        case $k in
            version) M_VERSION=$v ;;
            minimum_supported_version) M_MIN=$v ;;
            kill_switch) M_KILL=$v ;;
            artifact_url) M_URL=$v ;;
            artifact_sha256) M_SHA=$v ;;
            artifact_size) M_SIZE=$v ;;
            release_notes_url) M_NOTES=$v ;;
            generated_at) M_GEN=$v ;;
            expires_at) M_EXPIRES=$v ;;
            withdrawn_versions) M_WITHDRAWN=$v ;;
        esac
    done <<EOF
$sel
EOF
    case $M_GEN in
        [0-9][0-9][0-9][0-9]-[0-9][0-9]-[0-9][0-9]T[0-9][0-9]:[0-9][0-9]:[0-9][0-9]Z) ;;
        *) refuse 4 "update manifest has an invalid generated_at '$M_GEN'. Nothing was installed." ;;
    esac
}

# check_entry: shape checks on an entry read by read_manifest.
check_entry() {
    case $M_VERSION in
        [0-9]*.[0-9]*.[0-9]*) ;;
        *) refuse 4 "update manifest has an invalid version '$M_VERSION'" ;;
    esac
    case $M_VERSION in *[!0-9A-Za-z.+-]*) refuse 4 "update manifest has an invalid version '$M_VERSION'" ;; esac
    case $M_SHA in
        *[!0-9a-f]*|"") refuse 4 "update manifest has an invalid SHA-256" ;;
    esac
    [ ${#M_SHA} = 64 ] || refuse 4 "update manifest has an invalid SHA-256"
    case $M_SIZE in *[!0-9]*|"") refuse 4 "update manifest has an invalid size" ;; esac
    case $M_URL in
        https://*) ;;
        http://*) [ "$TEST_MODE" = 1 ] || refuse 4 "update manifest artifact URL is not HTTPS" ;;
        *) refuse 4 "update manifest artifact URL is not HTTPS" ;;
    esac
    case $M_URL in *[!0-9A-Za-z./:_%+=~-]*) refuse 4 "update manifest artifact URL has unexpected characters" ;; esac
}

# check_replay_floor: the live manifest must not be older than this installer's floor.
check_replay_floor() {
    if [ -n "$MIN_MANIFEST_GENERATED_AT" ] && str_lt "$M_GEN" "$MIN_MANIFEST_GENERATED_AT"; then
        refuse 4 "the $CHANNEL manifest was generated at $M_GEN, before $MIN_MANIFEST_GENERATED_AT, the oldest this installer accepts (a replayed old manifest?). Refusing. Nothing was installed."
    fi
}

# check_not_expired: the live manifest must not be past its expires_at. Installers keep no state,
# so this is their only freshness control: a withheld newer manifest cannot hide behind an old
# signed one for longer than its validity window. It is required of the live channel manifest
# only: the per-version manifests (integrity facts for a pinned or offline install, published once
# and kept) never expire, so read_manifest does not look at expires_at and a snapshot with or
# without it is accepted.
check_not_expired() {
    case $M_EXPIRES in
        [0-9][0-9][0-9][0-9]-[0-9][0-9]-[0-9][0-9]T[0-9][0-9]:[0-9][0-9]:[0-9][0-9]Z) ;;
        *) refuse 4 "update manifest has an invalid expires_at '$M_EXPIRES'. Nothing was installed." ;;
    esac
    if ! str_lt "$M_GEN" "$M_EXPIRES"; then
        refuse 4 "update manifest expires_at $M_EXPIRES is not after generated_at $M_GEN. Nothing was installed."
    fi
    now=${TEST_NOW:-$(date -u +%Y-%m-%dT%H:%M:%SZ)}
    if str_lt "$M_EXPIRES" "$now"; then
        refuse 4 "the $CHANNEL manifest expired at $M_EXPIRES (it is $now now). Check that this computer's clock is correct, or try again later. Refusing. Nothing was installed."
    fi
}

# check_live_allows VERSION: refuse a version the live channel manifest (LIVE_*) withdraws:
# listed as withdrawn, kill-switched, or below the channel's minimum supported version.
check_live_allows() {
    if list_has "$LIVE_WITHDRAWN" "$1"; then
        refuse 4 "version $1 has been withdrawn on the $CHANNEL channel. Nothing was installed."
    fi
    if [ -n "$LIVE_VERSION" ] && [ "$LIVE_VERSION" = "$1" ] && [ "$LIVE_KILL" = true ]; then
        refuse 4 "version $1 on the $CHANNEL channel has been withdrawn (kill switch). Nothing was installed."
    fi
    if [ -n "$LIVE_MIN" ] && [ "$(semver_cmp "$1" "$LIVE_MIN")" = -1 ]; then
        refuse 4 "version $1 is below the minimum supported version $LIVE_MIN of the $CHANNEL channel. Nothing was installed."
    fi
}

take_live() { LIVE_VERSION=$M_VERSION; LIVE_KILL=$M_KILL; LIVE_MIN=$M_MIN; LIVE_WITHDRAWN=$M_WITHDRAWN; }

# ---- install ----------------------------------------------------------------

do_install() {
    detect_target
    check_not_managed_elsewhere
    have curl || tdie 'curl is required'
    have unzip || have bsdtar || tdie 'unzip is required'

    # Create the state directory first, so a read-only prefix fails now,
    # before anything is downloaded.
    if ! mkdir -p "$SHARE" "$BIN" 2>/dev/null || [ ! -w "$SHARE" ] || [ ! -w "$BIN" ]; then
        trefuse 7 'cannot write to %s (read-only or no permission). Use --prefix with a directory you own. Nothing was installed.' "$PREFIX"
    fi
    take_lock
    STAGE=$SHARE/.staging.$$
    rm -rf "$STAGE"
    mkdir "$STAGE" || tdie 'cannot create %s' "$STAGE"
    chmod 700 "$STAGE"
    WORK=$STAGE/work
    mkdir "$WORK"

    # 1. Signed manifests. The live channel manifest is always consulted: it is the only
    # place a withdrawal, a kill switch or a raised minimum can appear, so even a pinned
    # version is checked against it. Only an offline --from install may go on without it.
    live_url=$MANIFEST_BASE/$CHANNEL/manifest.json
    LIVE_VERSION=""; LIVE_KILL=""; LIVE_MIN=""; LIVE_WITHDRAWN=""
    if [ -n "$FROM_FILE" ]; then
        [ -f "$FROM_FILE" ] || refuse 2 "--from: $FROM_FILE is not a file"
        FROM_DIR=$(cd "$(dirname "$FROM_FILE")" && pwd)
        cp "$FROM_FILE" "$WORK/from-envelope.json"
        verify_envelope "$WORK/from-envelope.json" "$WORK/from-manifest.json"
        say "Manifest signature verified (key $ENV_KEY), offline install from $FROM_FILE."
        read_manifest "$WORK/from-manifest.json"
        check_entry
        VERSION=$M_VERSION; URL=$M_URL; WANT_SHA=$M_SHA; WANT_SIZE=$M_SIZE; NOTES=$M_NOTES
        [ -z "$WANT_VERSION" ] || [ "$WANT_VERSION" = "$VERSION" ] ||
            refuse 4 "$FROM_FILE is for version $VERSION, not $WANT_VERSION. Nothing was installed."
        if [ "$M_KILL" = true ]; then
            refuse 4 "version $VERSION in $FROM_FILE is marked withdrawn (kill switch). Nothing was installed."
        fi
        # The supplied manifest's own withdrawals and minimum apply even when the live one is unreachable.
        take_live
        check_live_allows "$VERSION"
        LIVE_VERSION=""; LIVE_KILL=""; LIVE_MIN=""; LIVE_WITHDRAWN=""
        # The live manifest is checked when it can be reached; otherwise say so loudly.
        fetch_envelope "$live_url" "$WORK/envelope.json" && live_rc=0 || live_rc=$?
        if [ "$live_rc" = 0 ]; then
            UNPINNED_STATUS=22
            verify_envelope "$WORK/envelope.json" "$WORK/manifest.json"
            UNPINNED_STATUS=4
            read_manifest "$WORK/manifest.json" lenient
            check_replay_floor
            check_not_expired
            take_live
            check_live_allows "$VERSION"
            tsay 'The live %s manifest does not withdraw %s.' "$CHANNEL" "$VERSION"
        else
            terr 'WARNING: %s could not be reached (offline?), so it was NOT checked whether version %s has been withdrawn. Withdrawal not checked.' "$live_url" "$VERSION"
        fi
    else
        tsay 'Checking %s channel (%s)...' "$CHANNEL" "$TARGET"
        fetch_envelope "$live_url" "$WORK/envelope.json" && rc=0 || rc=$?
        case $rc in
            0) ;;
            1) tsay 'No release is published yet on the %s channel (no update manifest at %s).' "$CHANNEL" "$live_url"
               tsay 'Nothing was installed. Check https://yadori.link/ for the first release.'
               exit 1 ;;
            3) trefuse 3 'could not reach %s. Check your network connection. Nothing was installed.' "$live_url" ;;
            *) trefuse 3 'unexpected HTTP status %s from %s. Nothing was installed.' "$HTTP_CODE" "$live_url" ;;
        esac
        UNPINNED_STATUS=22
        verify_envelope "$WORK/envelope.json" "$WORK/manifest.json"
        UNPINNED_STATUS=4
        say "Manifest signature verified (key $ENV_KEY)."
        read_manifest "$WORK/manifest.json" lenient
        check_replay_floor
        check_not_expired
        take_live
        if [ -n "$WANT_VERSION" ] && [ "$WANT_VERSION" != "$LIVE_VERSION" ]; then
            # A pinned version: its signed per-version manifest proves integrity, the live
            # manifest decides whether it may still be installed.
            check_live_allows "$WANT_VERSION"
            snap_url=$MANIFEST_BASE/$WANT_VERSION/manifest.json
            fetch_envelope "$snap_url" "$WORK/snapshot-envelope.json" && rc=0 || rc=$?
            case $rc in
                0) ;;
                1) tdie 'version %s has no published manifest (%s). Nothing was installed.' "$WANT_VERSION" "$snap_url" ;;
                3) trefuse 3 'could not reach %s. Check your network connection. Nothing was installed.' "$snap_url" ;;
                *) trefuse 3 'unexpected HTTP status %s from %s. Nothing was installed.' "$HTTP_CODE" "$snap_url" ;;
            esac
            verify_envelope "$WORK/snapshot-envelope.json" "$WORK/snapshot.json"
            read_manifest "$WORK/snapshot.json"
            [ "$M_VERSION" = "$WANT_VERSION" ] ||
                refuse 4 "the manifest for $WANT_VERSION describes version $M_VERSION. Refusing. Nothing was installed."
        else
            read_manifest "$WORK/manifest.json"
        fi
        check_entry
        VERSION=$M_VERSION; URL=$M_URL; WANT_SHA=$M_SHA; WANT_SIZE=$M_SIZE; NOTES=$M_NOTES
        if [ "$M_KILL" = true ]; then
            refuse 4 "version $VERSION on the $CHANNEL channel has been withdrawn (kill switch). Nothing was installed."
        fi
        check_live_allows "$VERSION"
    fi

    installed=$(receipt_get version || true)
    if [ -n "$installed" ]; then
        rel=$(semver_cmp "$VERSION" "$installed")
        if [ "$rel" = 0 ] && [ "$FORCE" != 1 ] && [ "$(receipt_get channel)" = "$CHANNEL" ]; then
            tsay 'YadoriLink %s is already installed and up to date. (--force reinstalls.)' "$installed"
            setup_path
            return 0
        fi
        if [ "$rel" = -1 ]; then
            trefuse 6 'installed version %s is newer than %s on the %s channel; not downgrading. Nothing was changed.' "$installed" "$VERSION" "$CHANNEL"
        fi
    fi

    for name in yadorilink yadorilink-daemon; do
        if [ -e "$BIN/$name" ] || [ -L "$BIN/$name" ]; then
            is_ours "$BIN/$name" || tdie '%s/%s already exists and was not installed by this script. Remove it or choose another --prefix. Nothing was changed.' "$BIN" "$name"
        fi
    done

    if [ -n "$installed" ]; then
        confirm "$(tf 'Upgrade YadoriLink %s -> %s under %s?' "$installed" "$VERSION" "$PREFIX")" || tdie 'cancelled'
    else
        confirm "$(tf 'Install YadoriLink %s under %s?' "$VERSION" "$PREFIX")" || tdie 'cancelled'
    fi

    # 2. Bundle download and hashes against the signed manifest.
    zip_name=${URL##*/}
    ZIP=$STAGE/$zip_name
    if [ -n "$FROM_FILE" ]; then
        [ -f "$FROM_DIR/$zip_name" ] || refuse 2 "--from needs the engine bundle $zip_name next to $FROM_FILE. Nothing was installed."
        tsay 'Using %s (%s) from %s...' "$zip_name" "$VERSION" "$FROM_DIR"
        cp "$FROM_DIR/$zip_name" "$ZIP" || tdie 'cannot copy %s/%s. Nothing was installed.' "$FROM_DIR" "$zip_name"
    else
        tsay 'Downloading %s (%s)...' "$zip_name" "$VERSION"
        curl -sSL -f --max-redirs 5 --proto "$CURL_PROTO" --proto-redir "$CURL_PROTO" --tlsv1.2 --connect-timeout 15 --max-time 900 \
            --max-filesize "$WANT_SIZE" -o "$ZIP" "$URL" ||
            trefuse 3 'download failed or was interrupted (%s). Nothing was installed.' "$URL"
    fi
    [ "$(file_size "$ZIP")" = "$WANT_SIZE" ] || refuse 4 "downloaded bundle has the wrong size (expected $WANT_SIZE bytes). Refusing. Nothing was installed."
    [ "$(sha256_of "$ZIP")" = "$WANT_SHA" ] || refuse 4 "downloaded bundle SHA-256 does not match the signed manifest. Refusing. Nothing was installed."

    # 3. Unpack privately and verify the contents.
    EXTRACT=$STAGE/x
    mkdir "$EXTRACT"
    if have unzip; then
        names=$(unzip -Z1 "$ZIP") || refuse 4 "bundle is not a valid zip"
    else
        names=$(bsdtar -tf "$ZIP") || refuse 4 "bundle is not a valid zip"
    fi
    printf '%s\n' "$names" | awk '/^\// || /\\/ || /(^|\/)\.\.(\/|$)/ { bad = 1 } END { exit bad }' ||
        refuse 4 "bundle contains unsafe paths. Refusing. Nothing was installed."
    if have unzip; then unzip -q -o "$ZIP" -d "$EXTRACT" || tdie 'could not unpack the bundle'
    else bsdtar -xf "$ZIP" -C "$EXTRACT" || tdie 'could not unpack the bundle'; fi
    [ -z "$(find "$EXTRACT" -type l | head -n 1)" ] || refuse 4 "bundle contains symbolic links. Refusing. Nothing was installed."

    for f in SHA256SUMS engine-identity.json LICENSE SOURCE.txt THIRD-PARTY-LICENSES; do
        [ -f "$EXTRACT/$f" ] || refuse 4 "bundle is missing $f. Refusing. Nothing was installed."
    done
    # Every file except SHA256SUMS and engine-identity.json is listed with the
    # right hash, and nothing is unlisted.
    (cd "$EXTRACT" && find . -type f ! -name SHA256SUMS ! -name engine-identity.json | sed 's|^\./||' | LC_ALL=C sort) > "$WORK/actual.txt"
    sed -n 's/^[0-9a-f]\{64\}  //p' "$EXTRACT/SHA256SUMS" | LC_ALL=C sort > "$WORK/listed.txt"
    cmp -s "$WORK/actual.txt" "$WORK/listed.txt" || refuse 4 "bundle contents differ from its SHA256SUMS. Refusing. Nothing was installed."
    [ "$(grep -c . "$EXTRACT/SHA256SUMS")" = "$(grep -c . "$WORK/listed.txt")" ] || refuse 4 "SHA256SUMS is malformed. Refusing. Nothing was installed."
    while IFS= read -r line; do
        h=${line%%  *}
        p=${line#*  }
        [ "$(sha256_of "$EXTRACT/$p")" = "$h" ] || refuse 4 "bundle file $p does not match SHA256SUMS. Refusing. Nothing was installed."
    done < "$EXTRACT/SHA256SUMS"

    ident=$EXTRACT/engine-identity.json
    id_bundle=$(id_field "$ident" bundle_sha256) || refuse 4 "engine-identity.json is malformed (bundle_sha256)"
    [ "$(sha256_of "$EXTRACT/SHA256SUMS")" = "$id_bundle" ] || refuse 4 "engine identity does not cover this bundle's SHA256SUMS. Refusing. Nothing was installed."
    id_chan=$(id_field "$ident" channel) || refuse 4 "engine-identity.json is malformed (channel)"
    [ "$id_chan" = "$IDENTITY_CHANNEL" ] || refuse 4 "bundle is for channel '$id_chan', expected '$IDENTITY_CHANNEL'. Refusing. Nothing was installed."
    id_api=$(id_field "$ident" engine_api_version) || refuse 4 "engine-identity.json is malformed (engine_api_version)"
    id_commit=$(id_field "$ident" public_commit_sha) || refuse 4 "engine-identity.json is malformed (public_commit_sha)"
    case $id_commit in *[!0-9a-f]*|"") refuse 4 "engine identity has an invalid commit" ;; esac
    [ ${#id_commit} = 40 ] || refuse 4 "engine identity has an invalid commit"
    grep -qF "$id_commit" "$EXTRACT/SOURCE.txt" || refuse 4 "SOURCE.txt does not name the engine identity's source commit. Refusing. Nothing was installed."
    id_asset=$(id_field "$ident" asset_name) || refuse 4 "engine-identity.json is malformed (source.asset_name)"
    [ "$id_asset" = "$zip_name" ] || refuse 4 "engine identity names asset '$id_asset' but '$zip_name' was downloaded. Refusing. Nothing was installed."
    [ "$zip_name" = "yadorilink-engine-$id_chan-$TARGET.zip" ] || refuse 4 "bundle '$zip_name' is not the $TARGET engine bundle for channel $id_chan. Refusing. Nothing was installed."
    id_daemon=$(id_field "$ident" artifact_sha256) || refuse 4 "engine-identity.json is malformed (artifact_sha256)"
    [ "$(sha256_of "$EXTRACT/${BIN_SUBDIR}yadorilink-daemon")" = "$id_daemon" ] || refuse 4 "daemon does not match the engine identity. Refusing. Nothing was installed."
    for name in yadorilink yadorilink-daemon; do
        [ -f "$EXTRACT/$BIN_SUBDIR$name" ] || refuse 4 "bundle lacks $BIN_SUBDIR$name. Refusing. Nothing was installed."
        chmod 755 "$EXTRACT/$BIN_SUBDIR$name"
    done
    "$EXTRACT/${BIN_SUBDIR}yadorilink" --version >/dev/null 2>&1 ||
        tdie 'the new yadorilink does not run on this system (--version failed). Nothing was changed.'

    # The installer in the bundle was listed in SHA256SUMS and hashed above with everything else, so
    # this is the hash the signed chain vouches for.
    KEPT_INSTALLER_SHA=""
    if [ -f "$EXTRACT/install.sh" ]; then KEPT_INSTALLER_SHA=$(sha256_of "$EXTRACT/install.sh"); fi

    # The data already on this machine must be readable by what is about to be installed. Only the
    # bundle's own daemon knows its state versions, and the database is the only record of the
    # data's version, so it is asked to read it (read-only; nothing is created or changed).
    # Status 2 is a bundle from before the check existed: its daemon refuses newer data itself.
    compat_rc=0
    compat_out=$("$EXTRACT/${BIN_SUBDIR}yadorilink-daemon" --check-data-compat 2>&1 >/dev/null) || compat_rc=$?
    case $compat_rc in
        0) [ -z "$compat_out" ] || printf 'yadorilink-install: %s\n' "$compat_out" >&2 ;;
        2) say "note: this release does not check the existing data before installing" ;;
        20) refuse 20 "$compat_out Nothing was installed." ;;
        21) refuse 21 "$compat_out Nothing was installed." ;;
        *) refuse 21 "the data check of the new daemon failed unexpectedly (status $compat_rc): $compat_out Nothing was installed." ;;
    esac

    # The daemon recognises a script install by this file beside its binaries
    # (crates/yadorilink-daemon/src/update/install_source.rs). It lives in the
    # version tree, so it follows the binaries and is removed with them. Written
    # after verification; failing to write it aborts before anything is switched.
    printf '{"source":"script","version":"%s","channel":"%s"}\n' "$VERSION" "$CHANNEL" > "$EXTRACT/${BIN_SUBDIR}install-receipt.json" ||
        tdie 'could not write the install receipt beside the binaries. Nothing was changed.'

    # 4. Activate: stop the current install's daemon, move the verified tree into place, then switch the links.
    stop_old_daemon
    VDIR=versions/$VERSION.$(date +%s).$$
    mkdir -p "$SHARE/versions"
    mv "$EXTRACT" "$SHARE/$VDIR" || die "cannot move the verified bundle into place. Nothing was changed."
    old_dir=$(receipt_get dir || true)
    old_version=$(receipt_get version || true)
    old_prev=$(receipt_get previous_dir || true)

    # Switch the daemon link, then the CLI link; if a later step fails, put
    # the earlier links back.
    daemon_old=""
    if [ -L "$BIN/yadorilink-daemon" ]; then daemon_old=$(readlink "$BIN/yadorilink-daemon"); fi
    cli_old=""
    if [ -L "$BIN/yadorilink" ]; then cli_old=$(readlink "$BIN/yadorilink"); fi
    restore_links() {
        if [ -n "$daemon_old" ]; then set_link "$daemon_old" "$BIN/yadorilink-daemon" || true
        else rm -f "$BIN/yadorilink-daemon"; fi
        if [ -n "$cli_old" ]; then set_link "$cli_old" "$BIN/yadorilink" || true
        else rm -f "$BIN/yadorilink"; fi
    }
    set_link "$SHARE/$VDIR/${BIN_SUBDIR}yadorilink-daemon" "$BIN/yadorilink-daemon" ||
        { rm -rf "${SHARE:?}/$VDIR"; tdie 'could not switch %s/yadorilink-daemon. The previous install was kept.' "$BIN"; }
    if ! set_link "$SHARE/$VDIR/${BIN_SUBDIR}yadorilink" "$BIN/yadorilink"; then
        restore_links
        rm -rf "${SHARE:?}/$VDIR"
        tdie 'could not switch %s/yadorilink. The previous install was restored.' "$BIN"
    fi

    # The receipt is what uninstall and the next upgrade trust. If it cannot be
    # written, the links go back and the new tree is removed.
    if ! write_receipt; then
        rm -f "$SHARE/receipt.new.$$"
        restore_links
        rm -rf "${SHARE:?}/$VDIR"
        rmdir "$SHARE/versions" 2>/dev/null || true
        tdie 'could not write the install receipt. The previous install was restored.'
    fi

    # Drop only the version tree the previous receipt recorded as "previous"
    # (it is now two generations old). Nothing else under versions/ is ours to
    # delete.
    case $old_prev in
        "$SHARE"/versions/?*)
            if [ "$old_prev" != "$SHARE/$VDIR" ] && [ "$old_prev" != "$old_dir" ] && [ -d "$old_prev" ] && [ ! -L "$old_prev" ]; then
                rm -rf "$old_prev"
            fi ;;
    esac

    say ""
    tsay 'Installed YadoriLink %s (%s, %s) in %s.' "$VERSION" "$CHANNEL" "$TARGET" "$PREFIX"
    [ -z "$NOTES" ] || tsay 'Release notes: %s' "$NOTES"
    setup_path
    say ""
    start_daemon_or_say_how
    say ""
    tsay 'Next: sign in with'
    say "  yadorilink login"
    tsay 'Upgrade later by running the installer again. Remove with: install.sh --uninstall'
}

# Starts the daemon of the install just made, so the only step left is signing in. A start that
# does not take is not an install failure: the command that starts it is said instead.
start_daemon_or_say_how() {
    [ "$START_DAEMON" = 1 ] || { tsay 'The daemon was not started (--no-start). Start it with: yadorilink daemon start'; return 0; }
    if "$BIN/yadorilink" daemon start >/dev/null 2>&1; then
        if [ "${STOPPED_DAEMON:-0}" = 0 ]; then tsay 'YadoriLink is running.'
        else tsay 'The old daemon was stopped; the new one is running.'; fi
    else
        tsay 'The YadoriLink daemon could not be started. Start it with: yadorilink daemon start'
    fi
}

setup_path() {
    case ":$PATH:" in *":$BIN:"*) return 0 ;; esac
    if [ "$MODIFY_PATH" = 1 ]; then
        profile=$(path_profile)
        if ! grep -qF "$PATH_BEGIN" "$profile" 2>/dev/null; then
            {
                printf '\n%s\n' "$PATH_BEGIN"
                # Single-quote the directory so $, backticks and quotes in it stay literal.
                quoted=$(printf '%s' "$BIN" | sed "s/'/'\\\\''/g")
                # shellcheck disable=SC2016
                printf "export PATH='%s':\"\$PATH\"\n" "$quoted"
                printf '%s\n' "$PATH_END"
            } >> "$profile"
        fi
        PROFILE_VALUE=$profile awk '/^path_profile=/ { print "path_profile=" ENVIRON["PROFILE_VALUE"]; next } { print }' "$RECEIPT" > "$RECEIPT.new.$$" &&
            mv -f "$RECEIPT.new.$$" "$RECEIPT"
        tsay 'Added %s to your PATH in %s. Open a new terminal, or run:' "$BIN" "$profile"
    else
        tsay '%s is not on your PATH. Add it, for example:' "$BIN"
    fi
    say "  export PATH=\"$BIN:\$PATH\""
}

# do_rollback: switch back to the previous version this script installed. No network and no
# manifest: that tree was verified when it was installed, and here its files are checked against its
# own SHA256SUMS again (a changed file refuses). Nothing is deleted; the receipt's current and
# previous entries trade places, so a second rollback goes forward again.
do_rollback() {
    [ -f "$RECEIPT" ] || refuse 1 "nothing to roll back: no install receipt under $SHARE (this is not a script install). Nothing was changed."
    detect_target
    check_not_managed_elsewhere
    # Everything below is read and checked under the lock, so an upgrade cannot replace or prune
    # the trees between the checks and the switch.
    take_lock
    cur_dir=$(receipt_get dir || true)
    prev_dir=$(receipt_get previous_dir || true)
    cur_version=$(receipt_get version || true)
    prev_version=$(receipt_get previous_version || true)
    if [ -z "$prev_dir" ] || [ -z "$prev_version" ]; then
        refuse 1 "there is no previous version to go back to (the receipt records none). Nothing was changed."
    fi
    # Exactly one name under versions/: no separator, no dot components, and neither versions/ nor the
    # tree is a link, so the tree cannot be elsewhere.
    case $prev_dir in
        "$SHARE"/versions/?*) ;;
        *) refuse 1 "the receipt's previous version is not under $SHARE/versions. Nothing was changed." ;;
    esac
    prev_name=${prev_dir#"$SHARE"/versions/}
    case $prev_name in
        */*|.|..) refuse 1 "the receipt's previous version is not a plain directory under $SHARE/versions. Nothing was changed." ;;
    esac
    { [ -d "$SHARE/versions" ] && [ ! -L "$SHARE/versions" ]; } ||
        refuse 1 "$SHARE/versions is not a plain directory. Nothing was changed."
    { [ -d "$prev_dir" ] && [ ! -L "$prev_dir" ]; } ||
        refuse 1 "the previous version's files ($prev_dir) are gone. Nothing was changed. Run the one-line installer to install a version."
    [ "$prev_dir" != "$cur_dir" ] || refuse 1 "the previous and the current version are the same tree. Nothing was changed."
    [ -f "$prev_dir/SHA256SUMS" ] || refuse 4 "the previous version has no SHA256SUMS to check it by. Refusing. Nothing was changed."
    # Every file the previous tree's SHA256SUMS lists must still match it, and the programs must be there.
    # The list must be whole: tied to the engine identity the install verified, naming both programs,
    # and every file it lists must still match. A truncated list cannot vouch for anything.
    [ -f "$prev_dir/engine-identity.json" ] ||
        refuse 4 "the previous version has no engine identity to check its file list by. Refusing. Nothing was changed."
    id_sums=$(id_field "$prev_dir/engine-identity.json" bundle_sha256) ||
        refuse 4 "the previous version's engine identity is malformed. Refusing. Nothing was changed."
    [ "$(sha256_of "$prev_dir/SHA256SUMS")" = "$id_sums" ] ||
        refuse 4 "the previous version's SHA256SUMS no longer matches its engine identity. Refusing. Nothing was changed."
    bin_sub=""
    [ -f "$prev_dir/yadorilink" ] || { [ -f "$prev_dir/bin/yadorilink" ] && bin_sub=bin/; }
    for prog in yadorilink yadorilink-daemon; do
        grep -q "^[0-9a-f]\{64\}  ${bin_sub}${prog}\$" "$prev_dir/SHA256SUMS" ||
            refuse 4 "the previous version's file list does not name ${bin_sub}${prog}. Refusing. Nothing was changed."
    done
    checked=0
    while IFS= read -r line; do
        h=${line%%  *}
        p=${line#*  }
        [ "$(sha256_of "$prev_dir/$p" 2>/dev/null)" = "$h" ] ||
            refuse 4 "the previous version's file $p no longer matches its SHA256SUMS. Refusing. Nothing was changed."
        checked=$((checked + 1))
    done < "$prev_dir/SHA256SUMS"
    [ "$checked" -gt 0 ] || refuse 4 "the previous version's SHA256SUMS lists nothing. Refusing. Nothing was changed."
    { [ -f "$prev_dir/${bin_sub}yadorilink" ] && [ -f "$prev_dir/${bin_sub}yadorilink-daemon" ]; } ||
        refuse 4 "the previous version lacks its programs. Refusing. Nothing was changed."

    stop_old_daemon
    daemon_old=""
    if [ -L "$BIN/yadorilink-daemon" ]; then daemon_old=$(readlink "$BIN/yadorilink-daemon"); fi
    cli_old=""
    if [ -L "$BIN/yadorilink" ]; then cli_old=$(readlink "$BIN/yadorilink"); fi
    set_link "$prev_dir/${bin_sub}yadorilink-daemon" "$BIN/yadorilink-daemon" ||
        tdie 'could not switch %s/yadorilink-daemon. Nothing was changed.' "$BIN"
    if ! set_link "$prev_dir/${bin_sub}yadorilink" "$BIN/yadorilink"; then
        if [ -n "$daemon_old" ]; then set_link "$daemon_old" "$BIN/yadorilink-daemon" || true; fi
        tdie 'could not switch %s/yadorilink. The current version was restored.' "$BIN"
    fi
    # The values go in through the environment so a path with awk-special characters stays literal.
    if ! {
        YL_V=$prev_version YL_D=$prev_dir YL_PD=$cur_dir YL_PV=$cur_version \
            awk 'BEGIN { FS = OFS = "=" }
                 $1 == "version" { print "version=" ENVIRON["YL_V"]; next }
                 $1 == "dir" { print "dir=" ENVIRON["YL_D"]; next }
                 $1 == "previous_dir" { print "previous_dir=" ENVIRON["YL_PD"]; next }
                 $1 == "previous_version" { print "previous_version=" ENVIRON["YL_PV"]; next }
                 { print }' "$RECEIPT" > "$SHARE/receipt.new.$$" && mv -f "$SHARE/receipt.new.$$" "$RECEIPT"
    }; then
        rm -f "$SHARE/receipt.new.$$"
        if [ -n "$daemon_old" ]; then set_link "$daemon_old" "$BIN/yadorilink-daemon" || true; fi
        if [ -n "$cli_old" ]; then set_link "$cli_old" "$BIN/yadorilink" || true; fi
        tdie 'could not write the install receipt. The current version was restored.'
    fi
    tsay 'Rolled back to YadoriLink %s (from %s).' "$prev_version" "$cur_version"
    if [ "${STOPPED_DAEMON:-0}" = 1 ]; then tsay 'The running daemon was stopped. Start it again: yadorilink daemon start'
    else tsay 'No daemon was running. Start it with: yadorilink daemon start'; fi
}

main() {
    setup "$@"
    trap cleanup EXIT
    trap 'exit 130' INT
    trap 'exit 143' TERM
    trap 'exit 129' HUP
    case $ACTION in
        install) do_install ;;
        uninstall) do_uninstall ;;
        rollback) do_rollback ;;
    esac
}

main "$@"
