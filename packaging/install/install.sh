# ---- JSON extraction (awk; fails closed, the signature has already been
# checked when the manifest body is parsed) ----------------------------------

# envelope_field FILE KEY: the unescaped string value of KEY, exactly once.
envelope_field() {
    LC_ALL=C awk -v want="$2" '
    BEGIN { RS = "\001" }
    { s = $0 }
    END {
        pat = "\"" want "\""
        first = index(s, pat)
        if (first == 0) exit 3
        rest = substr(s, first + length(pat))
        if (index(rest, pat) != 0) exit 4
        n = length(rest); i = 1
        while (i <= n && substr(rest, i, 1) ~ /[ \t\r\n]/) i++
        if (substr(rest, i, 1) != ":") exit 5
        i++
        while (i <= n && substr(rest, i, 1) ~ /[ \t\r\n]/) i++
        if (substr(rest, i, 1) != "\"") exit 5
        i++
        out = ""
        while (i <= n) {
            c = substr(rest, i, 1)
            if (c == "\"") { printf "%s", out; exit 0 }
            if (c == "\\") {
                i++; e = substr(rest, i, 1)
                if (e == "\"" || e == "\\" || e == "/") out = out e
                else if (e == "n") out = out "\n"
                else if (e == "t") out = out "\t"
                else if (e == "r") out = out "\r"
                else if (e == "u") {
                    h = substr(rest, i + 1, 4)
                    if (h !~ /^00[0-7][0-9a-fA-F]$/ || h == "0000") exit 6
                    v = 0
                    for (j = 3; j <= 4; j++) v = v * 16 + index("0123456789abcdef", tolower(substr(h, j, 1))) - 1
                    out = out sprintf("%c", v); i += 4
                } else exit 6
            } else out = out c
            i++
        }
        exit 7
    }' "$1"
}

# select_entry FILE CHANNEL PLATFORM ARCH [lenient]: print "OK" then key=value lines
# of the one release entry whose channel, platform, arch and install_source
# ("script": the engine bundle for script installs) match, plus the manifest's
# generated_at and withdrawn_versions; otherwise an "ERR <reason>" line. In
# lenient mode a manifest without a matching entry still prints "OK" (with the
# entry fields empty): the live manifest of a channel is consulted for its
# withdrawals even when it has no entry for this platform.
select_entry() {
    LC_ALL=C awk -v ch="$2" -v pl="$3" -v ar="$4" -v lenient="${5:-}" '
    BEGIN { RS = "\001" }
    { body = $0 }
    function fail(m) { print "ERR " m; bad = 1; exit 0 }
    END {
        n = length(body); depth = 0; i = 1; key = ""; expectkey = 0; matches = 0; schema = ""; gen = ""; withdrawn = ""
        while (i <= n) {
            c = substr(body, i, 1)
            if (c ~ /[ \t\r\n,:]/) { i++; continue }
            if (c == "{") { depth++; expectkey = 0; if (depth == 3) { delete e } if (depth > 3) fail("unexpected nesting"); i++; continue }
            if (c == "[") { depth++; expectkey = 0; if (depth > 2) fail("unexpected nesting"); i++; continue }
            if (c == "}" || c == "]") {
                if (c == "}" && depth == 3) {
                    if (e["channel"] == ch && e["platform"] == pl && e["arch"] == ar && e["install_source"] == "script") {
                        matches++; for (k in e) sel[k] = e[k]
                    }
                }
                depth--; expectkey = 0; i++; continue
            }
            if (c == "\"") {
                j = i + 1; tok = ""
                while (j <= n && substr(body, j, 1) != "\"") {
                    if (substr(body, j, 1) == "\\") fail("escape in manifest field")
                    tok = tok substr(body, j, 1); j++
                }
                i = j + 1
            } else {
                j = i; tok = ""
                while (j <= n && substr(body, j, 1) !~ /[ \t\r\n,}\]]/) { tok = tok substr(body, j, 1); j++ }
                i = j
            }
            if (depth == 2 && key == "withdrawn_versions") { withdrawn = withdrawn (withdrawn == "" ? "" : " ") tok; continue }
            if (depth == 1 || depth == 3) {
                if (!expectkey) { key = tok; expectkey = 1 }
                else {
                    if (depth == 3) e[key] = tok
                    else if (key == "schema_version") schema = tok
                    else if (key == "generated_at") gen = tok
                    expectkey = 0
                }
            }
        }
        if (bad) exit 0
        if (schema != "2") fail("unsupported manifest schema_version")
        if (matches == 0 && lenient == "") fail("no matching release")
        if (matches > 1) fail("ambiguous releases")
        print "OK"
        split("version minimum_supported_version kill_switch artifact_url artifact_sha256 artifact_size release_notes_url", names, " ")
        for (q = 1; q <= 7; q++) print names[q] "=" sel[names[q]]
        print "generated_at=" gen
        print "withdrawn_versions=" withdrawn
    }' "$1"
}

# semver_cmp A B: print -1, 0 or 1 (A relative to B).
semver_cmp() {
    awk -v a="$1" -v b="$2" '
    function core(v, out,   t) { sub(/^v/, "", v); sub(/\+.*/, "", v); split(v, t, "-"); split(t[1], out, "."); return substr(v, length(t[1]) + 2) }
    BEGIN {
        pa = core(a, ca); pb = core(b, cb)
        for (i = 1; i <= 3; i++) {
            if (ca[i] + 0 < cb[i] + 0) { print -1; exit }
            if (ca[i] + 0 > cb[i] + 0) { print 1; exit }
        }
        if (pa == pb) { print 0; exit }
        if (pa == "") { print 1; exit }
        if (pb == "") { print -1; exit }
        na = split(pa, xa, "."); nb = split(pb, xb, ".")
        for (i = 1; i <= (na > nb ? na : nb); i++) {
            if (i > na) { print -1; exit }
            if (i > nb) { print 1; exit }
            numa = xa[i] ~ /^[0-9]+$/; numb = xb[i] ~ /^[0-9]+$/
            if (numa && numb) { if (xa[i] + 0 != xb[i] + 0) { print (xa[i] + 0 < xb[i] + 0) ? -1 : 1; exit } }
            else if (numa) { print -1; exit }
            else if (numb) { print 1; exit }
            else if (xa[i] != xb[i]) { print (xa[i] < xb[i]) ? -1 : 1; exit }
        }
        print 0
    }'
}

# id_field FILE KEY: the value of KEY in engine-identity.json (written with
# one key per line); exactly one occurrence or failure.
id_field() {
    vals=$(sed -n "s/^ *\"$2\": *\"\\([^\"]*\\)\" *,\\{0,1\\} *\$/\\1/p; s/^ *\"$2\": *\\([0-9][0-9]*\\) *,\\{0,1\\} *\$/\\1/p" "$1")
    [ -n "$vals" ] || return 1
    [ "$(printf '%s\n' "$vals" | wc -l | tr -d ' ')" = 1 ] || return 1
    printf '%s' "$vals"
}

# ---- platform ---------------------------------------------------------------

detect_target() {
    os=${TEST_OS:-$(uname -s)}
    machine=${TEST_ARCH:-$(uname -m)}
    case $os in
        Darwin|macos) PLATFORM=macos ;;
        Linux|linux) PLATFORM=linux ;;
        MINGW*|MSYS*|CYGWIN*|windows)
            refuse 5 "this is the macOS/Linux installer. On Windows use PowerShell: irm https://yadori.link/install.ps1 | iex" ;;
        *) refuse 5 "unsupported operating system '$os'. YadoriLink engine bundles exist for macOS (Apple silicon), Linux (x86_64) and Windows (x86_64)." ;;
    esac
    case $machine in
        arm64|aarch64) ARCH=aarch64 ;;
        x86_64|amd64) ARCH=x86_64 ;;
        *) refuse 5 "unsupported CPU '$machine'. YadoriLink engine bundles exist for macOS (Apple silicon), Linux (x86_64) and Windows (x86_64)." ;;
    esac
    # An x86_64 shell under Rosetta on Apple silicon still wants the native build.
    if [ -z "$TEST_OS" ] && [ "$PLATFORM" = macos ] && [ "$ARCH" = x86_64 ] &&
        [ "$(sysctl -n hw.optional.arm64 2>/dev/null || true)" = 1 ]; then
        ARCH=aarch64
    fi
    TARGET=$PLATFORM-$ARCH
    case $TARGET in
        macos-aarch64|linux-x86_64) ;;
        *) refuse 5 "no YadoriLink engine bundle for $TARGET yet (available: macos-aarch64, linux-x86_64, windows-x86_64). Nothing was installed." ;;
    esac
    if [ "$PLATFORM" = macos ]; then BIN_SUBDIR=bin/; else BIN_SUBDIR=""; fi
}

# ---- state ------------------------------------------------------------------

receipt_get() { [ -f "$RECEIPT" ] || return 0; sed -n "s/^$1=//p" "$RECEIPT" | head -n 1; }

cleanup() {
    status=$?
    if [ -n "${STAGE:-}" ] && [ -d "$STAGE" ]; then rm -rf "$STAGE"; fi
    if [ -n "${LOCKDIR:-}" ] && [ -d "$LOCKDIR" ] && [ "$(cat "$LOCKDIR/pid" 2>/dev/null)" = "$$" ]; then rm -rf "$LOCKDIR"; fi
    if [ -n "$WORK" ] && [ -d "$WORK" ]; then rm -rf "$WORK"; fi
    exit "$status"
}

take_lock() {
    LOCKDIR=$SHARE/.lock
    if ! mkdir "$LOCKDIR" 2>/dev/null; then
        other=$(cat "$LOCKDIR/pid" 2>/dev/null || true)
        if [ -z "$other" ]; then sleep 1; other=$(cat "$LOCKDIR/pid" 2>/dev/null || true); fi
        if [ -z "$other" ] && [ -d "$LOCKDIR" ]; then
            LOCKDIR=""
            die "another yadorilink install is starting, or left $SHARE/.lock behind; remove that directory if no install is running"
        fi
        if [ -n "$other" ] && kill -0 "$other" 2>/dev/null; then
            LOCKDIR=""
            die "another yadorilink install is running (pid $other)"
        fi
        rm -rf "$LOCKDIR"
        mkdir "$LOCKDIR" 2>/dev/null || { LOCKDIR=""; die "cannot take the install lock in $SHARE"; }
    fi
    printf '%s\n' "$$" > "$LOCKDIR/pid"
}

# set_link TARGET LINK: point LINK at TARGET atomically (temp link + rename).
set_link() {
    if ln -s "$1" "$2.new.$$" && mv -f "$2.new.$$" "$2"; then return 0; fi
    rm -f "$2.new.$$"
    return 1
}

# write_receipt: persist the install receipt for $VERSION in $VDIR (atomically).
write_receipt() {
    [ "$TEST_FAIL_RECEIPT" != 1 ] || return 1
    {
        printf 'version=%s\n' "$VERSION"
        printf 'dir=%s\n' "$SHARE/$VDIR"
        printf 'previous_dir=%s\n' "$old_dir"
        printf 'channel=%s\n' "$CHANNEL"
        printf 'target=%s\n' "$TARGET"
        printf 'engine_api_version=%s\n' "$id_api"
        printf 'install_source=script\n'
        printf 'path_profile=%s\n' "$(receipt_get path_profile || true)"
    } > "$SHARE/receipt.new.$$" && mv -f "$SHARE/receipt.new.$$" "$RECEIPT"
}

# is_ours LINK: true when LINK is a symlink into $SHARE.
is_ours() {
    [ -L "$1" ] || return 1
    case $(readlink "$1") in "$SHARE"/*) return 0 ;; *) return 1 ;; esac
}

path_profile() {
    case ${SHELL:-} in
        */zsh) printf '%s\n' "${ZDOTDIR:-$HOME}/.zshrc" ;;
        */bash)
            # Bash reads the first of these that exists when it is a login shell;
            # creating a new .bash_profile would hide an existing .profile.
            if [ "$(uname -s)" != Darwin ] && [ -f "$HOME/.bashrc" ]; then printf '%s\n' "$HOME/.bashrc"
            elif [ -f "$HOME/.bash_profile" ]; then printf '%s\n' "$HOME/.bash_profile"
            elif [ -f "$HOME/.bash_login" ]; then printf '%s\n' "$HOME/.bash_login"
            else printf '%s\n' "$HOME/.profile"; fi ;;
        *) printf '%s\n' "$HOME/.profile" ;;
    esac
}

remove_path_block() { # FILE
    [ -f "$1" ] || return 0
    grep -qF "$PATH_BEGIN" "$1" || return 0
    tmp=$1.yadorilink.$$
    PB=$PATH_BEGIN PE=$PATH_END awk '$0 == ENVIRON["PB"] { skip = 1; next } $0 == ENVIRON["PE"] { skip = 0; next } !skip' "$1" > "$tmp" &&
        cat "$tmp" > "$1"
    rm -f "$tmp"
}

# ---- uninstall --------------------------------------------------------------

do_uninstall() {
    if [ ! -d "$SHARE" ]; then
        say "Nothing to uninstall: no YadoriLink install found under $PREFIX."
        return 0
    fi
    confirm "Remove the YadoriLink install under $PREFIX?" || die "cancelled"
    take_lock
    for name in yadorilink yadorilink-daemon; do
        if is_ours "$BIN/$name"; then rm -f "$BIN/$name"; fi
    done
    profile=$(receipt_get path_profile)
    [ -z "$profile" ] || remove_path_block "$profile"
    rm -rf "$SHARE"
    rmdir "$BIN" 2>/dev/null || true
    say "Removed. Your sync data and sign-in are untouched; stop the daemon first with"
    say "'yadorilink daemon stop' if it is running, and remove its data directory yourself if you want it gone."
}

# ---- manifests ----------------------------------------------------------------

# str_lt A B: true when A sorts before B (fixed-width timestamps compare as text).
str_lt() { [ "$1" != "$2" ] && [ "$(printf '%s\n%s\n' "$1" "$2" | LC_ALL=C sort | head -n 1)" = "$1" ]; }

# list_has "a b c" X: true when X is one of the words.
list_has() { for w in $1; do [ "$w" = "$2" ] && return 0; done; return 1; }

# fetch_envelope URL OUT: download a signed envelope. Returns 0 (HTTP 200), 1 (404),
# 2 (another HTTP status, in $HTTP_CODE) or 3 (the network failed).
fetch_envelope() {
    HTTP_CODE=$(curl -sSL --max-redirs 5 --proto "$CURL_PROTO" --proto-redir "$CURL_PROTO" --tlsv1.2 --connect-timeout 15 --max-time 60 \
        --max-filesize 1048576 -o "$2" -w '%{http_code}' "$1") || return 3
    case $HTTP_CODE in 200) return 0 ;; 404) return 1 ;; *) return 2 ;; esac
}

# verify_envelope ENVFILE BODYFILE: check the key id and the Ed25519 signature against the
# pinned trust set and write the signed body to BODYFILE, or refuse (4).
verify_envelope() {
    env_key=$(envelope_field "$1" key_id) || refuse 4 "update manifest is malformed (key_id)"
    KEY_HEX=""
    for pair in $TRUST_SET; do
        [ "${pair%%:*}" = "$env_key" ] && KEY_HEX=${pair#*:}
    done
    [ -n "$KEY_HEX" ] || refuse 4 "update manifest is signed with key '$env_key', which is not one of the pinned release keys. Refusing. Nothing was installed."
    envelope_field "$1" manifest_json > "$2" || refuse 4 "update manifest is malformed (manifest_json)"
    sig_b64=$(envelope_field "$1" signature_base64) || refuse 4 "update manifest is malformed (signature_base64)"
    b64_to_file "$sig_b64" "$WORK/manifest.sig" || refuse 4 "update manifest signature is not valid base64"
    [ "$(file_size "$WORK/manifest.sig")" = 64 ] || refuse 4 "update manifest signature has the wrong length"
    [ -n "$VERIFIER" ] || fetch_verifier
    if ! ed25519_check "$KEY_HEX" "$2" "$WORK/manifest.sig"; then
        refuse 4 "the update manifest signature does NOT verify against the pinned release key. Refusing. Nothing was installed."
    fi
    ENV_KEY=$env_key
}

# read_manifest BODYFILE [lenient]: parse a verified body into the M_* variables for this
# channel, platform and architecture.
read_manifest() {
    sel=$(select_entry "$1" "$CHANNEL" "$PLATFORM" "$ARCH" "${2:-}") || die "cannot read the update manifest"
    case $sel in
        OK*) ;;
        *) refuse 4 "update manifest: ${sel#ERR } for $CHANNEL/$TARGET. Nothing was installed." ;;
    esac
    M_VERSION=""; M_KILL=""; M_URL=""; M_SHA=""; M_SIZE=""; M_NOTES=""; M_MIN=""; M_GEN=""; M_WITHDRAWN=""
    while IFS='=' read -r k v; do
        case $k in
            version) M_VERSION=$v ;;
            minimum_supported_version) M_MIN=$v ;;
            kill_switch) M_KILL=$v ;;
            artifact_url) M_URL=$v ;;
            artifact_sha256) M_SHA=$v ;;
            artifact_size) M_SIZE=$v ;;
            release_notes_url) M_NOTES=$v ;;
            generated_at) M_GEN=$v ;;
            withdrawn_versions) M_WITHDRAWN=$v ;;
        esac
    done <<EOF
$sel
EOF
    case $M_GEN in
        [0-9][0-9][0-9][0-9]-[0-9][0-9]-[0-9][0-9]T[0-9][0-9]:[0-9][0-9]:[0-9][0-9]Z) ;;
        *) refuse 4 "update manifest has an invalid generated_at '$M_GEN'. Nothing was installed." ;;
    esac
}

# check_entry: shape checks on an entry read by read_manifest.
check_entry() {
    case $M_VERSION in
        [0-9]*.[0-9]*.[0-9]*) ;;
        *) refuse 4 "update manifest has an invalid version '$M_VERSION'" ;;
    esac
    case $M_VERSION in *[!0-9A-Za-z.+-]*) refuse 4 "update manifest has an invalid version '$M_VERSION'" ;; esac
    case $M_SHA in
        *[!0-9a-f]*|"") refuse 4 "update manifest has an invalid SHA-256" ;;
    esac
    [ ${#M_SHA} = 64 ] || refuse 4 "update manifest has an invalid SHA-256"
    case $M_SIZE in *[!0-9]*|"") refuse 4 "update manifest has an invalid size" ;; esac
    case $M_URL in
        https://*) ;;
        http://*) [ "$TEST_MODE" = 1 ] || refuse 4 "update manifest artifact URL is not HTTPS" ;;
        *) refuse 4 "update manifest artifact URL is not HTTPS" ;;
    esac
    case $M_URL in *[!0-9A-Za-z./:_%+=~-]*) refuse 4 "update manifest artifact URL has unexpected characters" ;; esac
}

# check_replay_floor: the live manifest must not be older than this installer's floor.
check_replay_floor() {
    if [ -n "$MIN_MANIFEST_GENERATED_AT" ] && str_lt "$M_GEN" "$MIN_MANIFEST_GENERATED_AT"; then
        refuse 4 "the $CHANNEL manifest was generated at $M_GEN, before $MIN_MANIFEST_GENERATED_AT, the oldest this installer accepts (a replayed old manifest?). Refusing. Nothing was installed."
    fi
}

# check_live_allows VERSION: refuse a version the live channel manifest (LIVE_*) withdraws:
# listed as withdrawn, kill-switched, or below the channel's minimum supported version.
check_live_allows() {
    if list_has "$LIVE_WITHDRAWN" "$1"; then
        refuse 4 "version $1 has been withdrawn on the $CHANNEL channel. Nothing was installed."
    fi
    if [ -n "$LIVE_VERSION" ] && [ "$LIVE_VERSION" = "$1" ] && [ "$LIVE_KILL" = true ]; then
        refuse 4 "version $1 on the $CHANNEL channel has been withdrawn (kill switch). Nothing was installed."
    fi
    if [ -n "$LIVE_MIN" ] && [ "$(semver_cmp "$1" "$LIVE_MIN")" = -1 ]; then
        refuse 4 "version $1 is below the minimum supported version $LIVE_MIN of the $CHANNEL channel. Nothing was installed."
    fi
}

take_live() { LIVE_VERSION=$M_VERSION; LIVE_KILL=$M_KILL; LIVE_MIN=$M_MIN; LIVE_WITHDRAWN=$M_WITHDRAWN; }

# ---- install ----------------------------------------------------------------

do_install() {
    detect_target
    have curl || die "curl is required"
    have unzip || have bsdtar || die "unzip is required"

    # Create the state directory first, so a read-only prefix fails now,
    # before anything is downloaded.
    if ! mkdir -p "$SHARE" "$BIN" 2>/dev/null || [ ! -w "$SHARE" ] || [ ! -w "$BIN" ]; then
        refuse 7 "cannot write to $PREFIX (read-only or no permission). Use --prefix with a directory you own. Nothing was installed."
    fi
    take_lock
    STAGE=$SHARE/.staging.$$
    rm -rf "$STAGE"
    mkdir "$STAGE" || die "cannot create $STAGE"
    chmod 700 "$STAGE"
    WORK=$STAGE/work
    mkdir "$WORK"

    # 1. Signed manifests. The live channel manifest is always consulted: it is the only
    # place a withdrawal, a kill switch or a raised minimum can appear, so even a pinned
    # version is checked against it. Only an offline --from install may go on without it.
    live_url=$MANIFEST_BASE/$CHANNEL/manifest.json
    LIVE_VERSION=""; LIVE_KILL=""; LIVE_MIN=""; LIVE_WITHDRAWN=""
    if [ -n "$FROM_FILE" ]; then
        [ -f "$FROM_FILE" ] || refuse 2 "--from: $FROM_FILE is not a file"
        FROM_DIR=$(cd "$(dirname "$FROM_FILE")" && pwd)
        cp "$FROM_FILE" "$WORK/from-envelope.json"
        verify_envelope "$WORK/from-envelope.json" "$WORK/from-manifest.json"
        say "Manifest signature verified (key $ENV_KEY), offline install from $FROM_FILE."
        read_manifest "$WORK/from-manifest.json"
        check_entry
        VERSION=$M_VERSION; URL=$M_URL; WANT_SHA=$M_SHA; WANT_SIZE=$M_SIZE; NOTES=$M_NOTES
        [ -z "$WANT_VERSION" ] || [ "$WANT_VERSION" = "$VERSION" ] ||
            refuse 4 "$FROM_FILE is for version $VERSION, not $WANT_VERSION. Nothing was installed."
        if [ "$M_KILL" = true ]; then
            refuse 4 "version $VERSION in $FROM_FILE is marked withdrawn (kill switch). Nothing was installed."
        fi
        # The supplied manifest's own withdrawals and minimum apply even when the live one is unreachable.
        take_live
        check_live_allows "$VERSION"
        LIVE_VERSION=""; LIVE_KILL=""; LIVE_MIN=""; LIVE_WITHDRAWN=""
        # The live manifest is checked when it can be reached; otherwise say so loudly.
        fetch_envelope "$live_url" "$WORK/envelope.json" && live_rc=0 || live_rc=$?
        if [ "$live_rc" = 0 ]; then
            verify_envelope "$WORK/envelope.json" "$WORK/manifest.json"
            read_manifest "$WORK/manifest.json" lenient
            check_replay_floor
            take_live
            check_live_allows "$VERSION"
            say "The live $CHANNEL manifest does not withdraw $VERSION."
        else
            err "WARNING: $live_url could not be reached (offline?), so it was NOT checked whether version $VERSION has been withdrawn. Withdrawal not checked."
        fi
    else
        say "Checking $CHANNEL channel ($TARGET)..."
        fetch_envelope "$live_url" "$WORK/envelope.json" && rc=0 || rc=$?
        case $rc in
            0) ;;
            1) say "No release is published yet on the $CHANNEL channel (no update manifest at $live_url)."
               say "Nothing was installed. Check https://yadori.link/ for the first release."
               exit 1 ;;
            3) refuse 3 "could not reach $live_url. Check your network connection. Nothing was installed." ;;
            *) refuse 3 "unexpected HTTP status $HTTP_CODE from $live_url. Nothing was installed." ;;
        esac
        verify_envelope "$WORK/envelope.json" "$WORK/manifest.json"
        say "Manifest signature verified (key $ENV_KEY)."
        read_manifest "$WORK/manifest.json" lenient
        check_replay_floor
        take_live
        if [ -n "$WANT_VERSION" ] && [ "$WANT_VERSION" != "$LIVE_VERSION" ]; then
            # A pinned version: its signed per-version manifest proves integrity, the live
            # manifest decides whether it may still be installed.
            check_live_allows "$WANT_VERSION"
            snap_url=$MANIFEST_BASE/$WANT_VERSION/manifest.json
            fetch_envelope "$snap_url" "$WORK/snapshot-envelope.json" && rc=0 || rc=$?
            case $rc in
                0) ;;
                1) die "version $WANT_VERSION has no published manifest ($snap_url). Nothing was installed." ;;
                3) refuse 3 "could not reach $snap_url. Check your network connection. Nothing was installed." ;;
                *) refuse 3 "unexpected HTTP status $HTTP_CODE from $snap_url. Nothing was installed." ;;
            esac
            verify_envelope "$WORK/snapshot-envelope.json" "$WORK/snapshot.json"
            read_manifest "$WORK/snapshot.json"
            [ "$M_VERSION" = "$WANT_VERSION" ] ||
                refuse 4 "the manifest for $WANT_VERSION describes version $M_VERSION. Refusing. Nothing was installed."
        else
            read_manifest "$WORK/manifest.json"
        fi
        check_entry
        VERSION=$M_VERSION; URL=$M_URL; WANT_SHA=$M_SHA; WANT_SIZE=$M_SIZE; NOTES=$M_NOTES
        if [ "$M_KILL" = true ]; then
            refuse 4 "version $VERSION on the $CHANNEL channel has been withdrawn (kill switch). Nothing was installed."
        fi
        check_live_allows "$VERSION"
    fi

    installed=$(receipt_get version || true)
    if [ -n "$installed" ]; then
        rel=$(semver_cmp "$VERSION" "$installed")
        if [ "$rel" = 0 ] && [ "$FORCE" != 1 ] && [ "$(receipt_get channel)" = "$CHANNEL" ]; then
            say "YadoriLink $installed is already installed and up to date. (--force reinstalls.)"
            setup_path
            return 0
        fi
        if [ "$rel" = -1 ]; then
            refuse 6 "installed version $installed is newer than $VERSION on the $CHANNEL channel; not downgrading. Nothing was changed."
        fi
    fi

    for name in yadorilink yadorilink-daemon; do
        if [ -e "$BIN/$name" ] || [ -L "$BIN/$name" ]; then
            is_ours "$BIN/$name" || die "$BIN/$name already exists and was not installed by this script. Remove it or choose another --prefix. Nothing was changed."
        fi
    done

    if [ -n "$installed" ]; then
        confirm "Upgrade YadoriLink $installed -> $VERSION under $PREFIX?" || die "cancelled"
    else
        confirm "Install YadoriLink $VERSION under $PREFIX?" || die "cancelled"
    fi

    # 2. Bundle download and hashes against the signed manifest.
    zip_name=${URL##*/}
    ZIP=$STAGE/$zip_name
    if [ -n "$FROM_FILE" ]; then
        [ -f "$FROM_DIR/$zip_name" ] || refuse 2 "--from needs the engine bundle $zip_name next to $FROM_FILE. Nothing was installed."
        say "Using $zip_name ($VERSION) from $FROM_DIR..."
        cp "$FROM_DIR/$zip_name" "$ZIP" || die "cannot copy $FROM_DIR/$zip_name. Nothing was installed."
    else
        say "Downloading $zip_name ($VERSION)..."
        curl -sSL -f --max-redirs 5 --proto "$CURL_PROTO" --proto-redir "$CURL_PROTO" --tlsv1.2 --connect-timeout 15 --max-time 900 \
            --max-filesize "$WANT_SIZE" -o "$ZIP" "$URL" ||
            refuse 3 "download failed or was interrupted ($URL). Nothing was installed."
    fi
    [ "$(file_size "$ZIP")" = "$WANT_SIZE" ] || refuse 4 "downloaded bundle has the wrong size (expected $WANT_SIZE bytes). Refusing. Nothing was installed."
    [ "$(sha256_of "$ZIP")" = "$WANT_SHA" ] || refuse 4 "downloaded bundle SHA-256 does not match the signed manifest. Refusing. Nothing was installed."

    # 3. Unpack privately and verify the contents.
    EXTRACT=$STAGE/x
    mkdir "$EXTRACT"
    if have unzip; then
        names=$(unzip -Z1 "$ZIP") || refuse 4 "bundle is not a valid zip"
    else
        names=$(bsdtar -tf "$ZIP") || refuse 4 "bundle is not a valid zip"
    fi
    printf '%s\n' "$names" | awk '/^\// || /\\/ || /(^|\/)\.\.(\/|$)/ { bad = 1 } END { exit bad }' ||
        refuse 4 "bundle contains unsafe paths. Refusing. Nothing was installed."
    if have unzip; then unzip -q -o "$ZIP" -d "$EXTRACT" || die "could not unpack the bundle"
    else bsdtar -xf "$ZIP" -C "$EXTRACT" || die "could not unpack the bundle"; fi
    [ -z "$(find "$EXTRACT" -type l | head -n 1)" ] || refuse 4 "bundle contains symbolic links. Refusing. Nothing was installed."

    for f in SHA256SUMS engine-identity.json LICENSE SOURCE.txt THIRD-PARTY-LICENSES; do
        [ -f "$EXTRACT/$f" ] || refuse 4 "bundle is missing $f. Refusing. Nothing was installed."
    done
    # Every file except SHA256SUMS and engine-identity.json is listed with the
    # right hash, and nothing is unlisted.
    (cd "$EXTRACT" && find . -type f ! -name SHA256SUMS ! -name engine-identity.json | sed 's|^\./||' | LC_ALL=C sort) > "$WORK/actual.txt"
    sed -n 's/^[0-9a-f]\{64\}  //p' "$EXTRACT/SHA256SUMS" | LC_ALL=C sort > "$WORK/listed.txt"
    cmp -s "$WORK/actual.txt" "$WORK/listed.txt" || refuse 4 "bundle contents differ from its SHA256SUMS. Refusing. Nothing was installed."
    [ "$(grep -c . "$EXTRACT/SHA256SUMS")" = "$(grep -c . "$WORK/listed.txt")" ] || refuse 4 "SHA256SUMS is malformed. Refusing. Nothing was installed."
    while IFS= read -r line; do
        h=${line%%  *}
        p=${line#*  }
        [ "$(sha256_of "$EXTRACT/$p")" = "$h" ] || refuse 4 "bundle file $p does not match SHA256SUMS. Refusing. Nothing was installed."
    done < "$EXTRACT/SHA256SUMS"

    ident=$EXTRACT/engine-identity.json
    id_bundle=$(id_field "$ident" bundle_sha256) || refuse 4 "engine-identity.json is malformed (bundle_sha256)"
    [ "$(sha256_of "$EXTRACT/SHA256SUMS")" = "$id_bundle" ] || refuse 4 "engine identity does not cover this bundle's SHA256SUMS. Refusing. Nothing was installed."
    id_chan=$(id_field "$ident" channel) || refuse 4 "engine-identity.json is malformed (channel)"
    [ "$id_chan" = "$IDENTITY_CHANNEL" ] || refuse 4 "bundle is for channel '$id_chan', expected '$IDENTITY_CHANNEL'. Refusing. Nothing was installed."
    id_api=$(id_field "$ident" engine_api_version) || refuse 4 "engine-identity.json is malformed (engine_api_version)"
    id_commit=$(id_field "$ident" public_commit_sha) || refuse 4 "engine-identity.json is malformed (public_commit_sha)"
    case $id_commit in *[!0-9a-f]*|"") refuse 4 "engine identity has an invalid commit" ;; esac
    [ ${#id_commit} = 40 ] || refuse 4 "engine identity has an invalid commit"
    grep -qF "$id_commit" "$EXTRACT/SOURCE.txt" || refuse 4 "SOURCE.txt does not name the engine identity's source commit. Refusing. Nothing was installed."
    id_asset=$(id_field "$ident" asset_name) || refuse 4 "engine-identity.json is malformed (source.asset_name)"
    [ "$id_asset" = "$zip_name" ] || refuse 4 "engine identity names asset '$id_asset' but '$zip_name' was downloaded. Refusing. Nothing was installed."
    [ "$zip_name" = "yadorilink-engine-$id_chan-$TARGET.zip" ] || refuse 4 "bundle '$zip_name' is not the $TARGET engine bundle for channel $id_chan. Refusing. Nothing was installed."
    id_daemon=$(id_field "$ident" artifact_sha256) || refuse 4 "engine-identity.json is malformed (artifact_sha256)"
    [ "$(sha256_of "$EXTRACT/${BIN_SUBDIR}yadorilink-daemon")" = "$id_daemon" ] || refuse 4 "daemon does not match the engine identity. Refusing. Nothing was installed."
    for name in yadorilink yadorilink-daemon; do
        [ -f "$EXTRACT/$BIN_SUBDIR$name" ] || refuse 4 "bundle lacks $BIN_SUBDIR$name. Refusing. Nothing was installed."
        chmod 755 "$EXTRACT/$BIN_SUBDIR$name"
    done
    "$EXTRACT/${BIN_SUBDIR}yadorilink" --version >/dev/null 2>&1 ||
        die "the new yadorilink does not run on this system (--version failed). Nothing was changed."

    # The daemon recognises a script install by this file beside its binaries
    # (crates/yadorilink-daemon/src/update/install_source.rs). It lives in the
    # version tree, so it follows the binaries and is removed with them. Written
    # after verification; failing to write it aborts before anything is switched.
    printf '{"source":"script","version":"%s","channel":"%s"}\n' "$VERSION" "$CHANNEL" > "$EXTRACT/${BIN_SUBDIR}install-receipt.json" ||
        die "could not write the install receipt beside the binaries. Nothing was changed."

    # 4. Activate: move the verified tree into place, then switch the links.
    VDIR=versions/$VERSION.$(date +%s).$$
    mkdir -p "$SHARE/versions"
    mv "$EXTRACT" "$SHARE/$VDIR" || die "cannot move the verified bundle into place. Nothing was changed."
    old_dir=$(receipt_get dir || true)
    old_prev=$(receipt_get previous_dir || true)

    # Switch the daemon link, then the CLI link; if a later step fails, put
    # the earlier links back.
    daemon_old=""
    if [ -L "$BIN/yadorilink-daemon" ]; then daemon_old=$(readlink "$BIN/yadorilink-daemon"); fi
    cli_old=""
    if [ -L "$BIN/yadorilink" ]; then cli_old=$(readlink "$BIN/yadorilink"); fi
    restore_links() {
        if [ -n "$daemon_old" ]; then set_link "$daemon_old" "$BIN/yadorilink-daemon" || true
        else rm -f "$BIN/yadorilink-daemon"; fi
        if [ -n "$cli_old" ]; then set_link "$cli_old" "$BIN/yadorilink" || true
        else rm -f "$BIN/yadorilink"; fi
    }
    set_link "$SHARE/$VDIR/${BIN_SUBDIR}yadorilink-daemon" "$BIN/yadorilink-daemon" ||
        { rm -rf "${SHARE:?}/$VDIR"; die "could not switch $BIN/yadorilink-daemon. The previous install was kept."; }
    if ! set_link "$SHARE/$VDIR/${BIN_SUBDIR}yadorilink" "$BIN/yadorilink"; then
        restore_links
        rm -rf "${SHARE:?}/$VDIR"
        die "could not switch $BIN/yadorilink. The previous install was restored."
    fi

    # The receipt is what uninstall and the next upgrade trust. If it cannot be
    # written, the links go back and the new tree is removed.
    if ! write_receipt; then
        rm -f "$SHARE/receipt.new.$$"
        restore_links
        rm -rf "${SHARE:?}/$VDIR"
        rmdir "$SHARE/versions" 2>/dev/null || true
        die "could not write the install receipt. The previous install was restored."
    fi

    # Drop only the version tree the previous receipt recorded as "previous"
    # (it is now two generations old). Nothing else under versions/ is ours to
    # delete.
    case $old_prev in
        "$SHARE"/versions/?*)
            if [ "$old_prev" != "$SHARE/$VDIR" ] && [ "$old_prev" != "$old_dir" ] && [ -d "$old_prev" ] && [ ! -L "$old_prev" ]; then
                rm -rf "$old_prev"
            fi ;;
    esac

    say ""
    say "Installed YadoriLink $VERSION ($CHANNEL, $TARGET) in $PREFIX."
    [ -z "$NOTES" ] || say "Release notes: $NOTES"
    setup_path
    say ""
    say "Next steps:"
    say "  yadorilink daemon start"
    say "  yadorilink login"
    say "Upgrade later by running the installer again. Remove with: install.sh --uninstall"
}

setup_path() {
    case ":$PATH:" in *":$BIN:"*) return 0 ;; esac
    if [ "$MODIFY_PATH" = 1 ]; then
        profile=$(path_profile)
        if ! grep -qF "$PATH_BEGIN" "$profile" 2>/dev/null; then
            {
                printf '\n%s\n' "$PATH_BEGIN"
                # Single-quote the directory so $, backticks and quotes in it stay literal.
                quoted=$(printf '%s' "$BIN" | sed "s/'/'\\\\''/g")
                # shellcheck disable=SC2016
                printf "export PATH='%s':\"\$PATH\"\n" "$quoted"
                printf '%s\n' "$PATH_END"
            } >> "$profile"
        fi
        PROFILE_VALUE=$profile awk '/^path_profile=/ { print "path_profile=" ENVIRON["PROFILE_VALUE"]; next } { print }' "$RECEIPT" > "$RECEIPT.new.$$" &&
            mv -f "$RECEIPT.new.$$" "$RECEIPT"
        say "Added $BIN to your PATH in $profile. Open a new terminal, or run:"
    else
        say "$BIN is not on your PATH. Add it, for example:"
    fi
    say "  export PATH=\"$BIN:\$PATH\""
}

main() {
    setup "$@"
    trap cleanup EXIT
    trap 'exit 130' INT
    trap 'exit 143' TERM
    trap 'exit 129' HUP
    case $ACTION in
        install) do_install ;;
        uninstall) do_uninstall ;;
    esac
}

main "$@"
