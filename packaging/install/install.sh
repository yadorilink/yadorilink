#!/bin/sh
# YadoriLink installer for macOS (Apple silicon) and Linux (x86_64).
#
#   curl -fsSL https://yadori.link/install.sh | sh
#   curl -fsSL https://yadori.link/install.sh | sh -s -- --channel beta --yes
#
# Prefer to read it first? See https://yadori.link/#install ("verify first").
#
# What it does, in order, and nothing else:
#   1. Fetches the signed update manifest for the channel over HTTPS and
#      verifies its Ed25519 signature against the pinned release keys, using a
#      small verifier program whose SHA-256 is pinned in this script.
#   2. Downloads the engine bundle the signed manifest names and checks its
#      size and SHA-256 against the manifest.
#   3. Unpacks it in a private staging directory and checks every file against
#      the SHA256SUMS inside the bundle, SHA256SUMS against engine-identity.json,
#      and the identity's channel, platform and source.
#   4. Only then switches the two program links (yadorilink,
#      yadorilink-daemon) in <prefix>/bin to the new version. The previous
#      version stays on disk until the next upgrade. Any failure before this
#      step leaves an existing install untouched.
# It never uses sudo, never runs anything from the bundle before the checks
# pass (then only `yadorilink --version`), and never starts the daemon.
#
# Options:
#   --prefix DIR       install under DIR (default: $HOME/.local; programs in DIR/bin)
#   --channel NAME     beta (default) or nightly
#   --version X.Y.Z    install exactly this version (env: YADORILINK_VERSION).
#                      The channel's current version, or an older one from its
#                      signed per-version manifest; both are also checked against
#                      the live channel manifest, which can withdraw a version
#   --from FILE        offline install: FILE is a signed manifest envelope (a
#                      channel or per-version manifest); the engine zip and the
#                      pinned verifier program sit next to it. If the live channel
#                      manifest is reachable it must not withdraw the version;
#                      if it is not, a loud warning says withdrawal was not checked
#   --no-modify-path   do not edit a shell profile
#   --yes, -y          do not ask for confirmation
#   --force            reinstall even if this version is already installed
#   --uninstall        remove what this script installed
#   --help, -h         show this text
#
# Exit status: 0 ok or already current, 1 other failure, 2 usage, 3 network,
# 4 signature, hash, replay or withdrawal refusal, 5 unsupported platform,
# 6 downgrade refused, 7 prefix not writable.
#
# Needs: curl, unzip, awk, and sha256sum or shasum. The Ed25519 signature is
# checked by a small pinned verifier program the script downloads and hash-checks
# first (see "Ed25519 verification" below); OpenSSL is not needed.

set -eu

# ---- pins ---------------------------------------------------------------
# Everything between the two PINS markers is generated by installer-sync from the
# release trust set (never edited by hand; packaging/install/pins.py renders and
# checks it, and landing CI compares it with the attested release).
#   TRUST_SET  space-separated "key_id:public_key_hex", the current key first and
#              the next key after it during a rotation. A manifest is accepted
#              only if its key_id is in this set and its signature verifies
#              under that entry's key.
#   VERIFIER_SHA_*  SHA-256 of the signature verifier program per platform
#              (empty until the verifier is released; the installer then
#              refuses with a clear message).
#   MIN_MANIFEST_GENERATED_AT  the oldest channel manifest this installer
#              accepts (a replay floor for a first install; empty = none).
# >>> PINS >>>
TRUST_SET="yadorilink-release-2026-10:cdaf6fbf36a6fa5c8c894fc5012a80bb6c6a73407c9285ac8623d572e9894bd8"
VERIFIER_SHA_macos_aarch64=""
VERIFIER_SHA_linux_x86_64=""
VERIFIER_BASE="https://github.com/yadorilink/yadorilink/releases/download/verifier-1"
MIN_MANIFEST_GENERATED_AT=""
# <<< PINS <<<
MANIFEST_BASE="https://yadori.link/dl"
CURL_PROTO="=https"

# Test hooks. Honoured ONLY when YADORILINK_INSTALL_TEST=1, which a real
# install never sets. They let the test suite run against a local fixture
# release signed by a throw-away key.
TEST_MODE=0
TEST_OS=""
TEST_ARCH=""
TEST_VERIFIER_SHA=""
TEST_FAIL_RECEIPT=0
if [ "${YADORILINK_INSTALL_TEST:-}" = "1" ]; then
    TEST_MODE=1
    if [ -n "${YADORILINK_INSTALL_PUBKEY_HEX:-}" ]; then
        TRUST_SET="${YADORILINK_INSTALL_KEY_ID:-test-key}:$YADORILINK_INSTALL_PUBKEY_HEX"
    fi
    TRUST_SET=${YADORILINK_INSTALL_TRUST_SET:-$TRUST_SET}
    VERIFIER_BASE=${YADORILINK_INSTALL_VERIFIER_BASE:-$VERIFIER_BASE}
    TEST_VERIFIER_SHA=${YADORILINK_INSTALL_VERIFIER_SHA256:-}
    MANIFEST_BASE=${YADORILINK_INSTALL_BASE_URL:-$MANIFEST_BASE}
    MIN_MANIFEST_GENERATED_AT=${YADORILINK_INSTALL_MIN_GENERATED_AT:-$MIN_MANIFEST_GENERATED_AT}
    TEST_OS=${YADORILINK_INSTALL_OS:-}
    TEST_ARCH=${YADORILINK_INSTALL_ARCH:-}
    TEST_FAIL_RECEIPT=${YADORILINK_INSTALL_FAIL_RECEIPT:-0}
    CURL_PROTO="=http,https"
    printf 'yadorilink-install: TEST MODE (trust root and endpoints overridden)\n' >&2
fi

PREFIX=${YADORILINK_PREFIX:-}
CHANNEL=${YADORILINK_CHANNEL:-beta}
WANT_VERSION=${YADORILINK_VERSION:-}
FROM_FILE=""
FROM_DIR=""
MODIFY_PATH=1
ASSUME_YES=0
FORCE=0
ACTION=install

say() { printf '%s\n' "$*"; }
err() { printf 'yadorilink-install: error: %s\n' "$*" >&2; }
die() { err "$*"; exit 1; }
# refuse CODE MESSAGE: print the reason and exit with CODE (see "Exit status" above).
refuse() { code=$1; shift; err "$*"; exit "$code"; }

usage() {
    # Print the header comment block (everything up to the first blank line
    # after "Options:").
    awk 'NR==1{next} /^set -eu/{exit} /^#/{sub(/^# ?/,""); print}' "$0" 2>/dev/null ||
        say "usage: install.sh [--prefix DIR] [--channel beta|nightly] [--version X.Y.Z] [--from FILE] [--no-modify-path] [--yes] [--force] [--uninstall]"
}

# parse_args and derive paths. All work happens in main, called on the last
# line, so a truncated download runs nothing.
setup() {
    while [ $# -gt 0 ]; do
        case $1 in
            --prefix) [ $# -ge 2 ] || refuse 2 "--prefix needs a directory"; PREFIX=$2; shift 2 ;;
            --prefix=*) PREFIX=${1#--prefix=}; shift ;;
            --channel) [ $# -ge 2 ] || refuse 2 "--channel needs a name"; CHANNEL=$2; shift 2 ;;
            --channel=*) CHANNEL=${1#--channel=}; shift ;;
            --version) [ $# -ge 2 ] || refuse 2 "--version needs a value"; WANT_VERSION=$2; shift 2 ;;
            --version=*) WANT_VERSION=${1#--version=}; shift ;;
            --from) [ $# -ge 2 ] || refuse 2 "--from needs a file"; FROM_FILE=$2; shift 2 ;;
            --from=*) FROM_FILE=${1#--from=}; shift ;;
            --no-modify-path) MODIFY_PATH=0; shift ;;
            --yes|-y) ASSUME_YES=1; shift ;;
            --force) FORCE=1; shift ;;
            --uninstall) ACTION=uninstall; shift ;;
            --help|-h) usage; exit 0 ;;
            *) refuse 2 "unknown option: $1 (try --help)" ;;
        esac
    done

    case $CHANNEL in
        beta) IDENTITY_CHANNEL=beta ;;
        nightly) IDENTITY_CHANNEL=dev ;;
        *) refuse 2 "unknown channel '$CHANNEL' (published channels: beta, nightly)" ;;
    esac
    WANT_VERSION=${WANT_VERSION#v}

    [ -n "${HOME:-}" ] || die "HOME is not set"
    [ -n "$PREFIX" ] || PREFIX=$HOME/.local
    case $PREFIX in
        /*) ;;
        *) refuse 2 "--prefix must be an absolute path" ;;
    esac
    BIN=$PREFIX/bin
    SHARE=$PREFIX/share/yadorilink
    RECEIPT=$SHARE/install-receipt
    PATH_BEGIN="# >>> yadorilink ($PREFIX) >>>"
    PATH_END="# <<< yadorilink ($PREFIX) <<<"
}

# ---- helpers ----------------------------------------------------------------

have() { command -v "$1" >/dev/null 2>&1; }

sha256_of() {
    if have sha256sum; then sha256sum "$1" | awk '{print $1}'
    elif have shasum; then shasum -a 256 "$1" | awk '{print $1}'
    elif have openssl; then openssl dgst -sha256 "$1" | awk '{print $NF}'
    else die "need sha256sum, shasum or openssl to check downloads"
    fi
}

file_size() { wc -c < "$1" | tr -d ' '; }

# hex_to_file HEX OUT: write the bytes HEX spells (lowercase hex) to OUT.
hex_to_file() {
    esc=$(printf '%s' "$1" | awk '{
        n = length($0)
        for (i = 1; i < n; i += 2) {
            v = 0
            for (j = 0; j < 2; j++) v = v * 16 + index("0123456789abcdef", substr($0, i + j, 1)) - 1
            printf "\\%03o", v
        }
    }')
    # shellcheck disable=SC2059  # the format is octal escapes built above
    printf "$esc" > "$2"
}

b64_to_file() { # B64 OUT
    if printf '%s' "$1" | base64 -d > "$2" 2>/dev/null; then :
    elif printf '%s' "$1" | base64 -D > "$2" 2>/dev/null; then :
    elif have openssl && printf '%s' "$1" | openssl base64 -d -A > "$2" 2>/dev/null; then :
    else return 1
    fi
}

confirm() { # PROMPT; true when ok to continue
    [ "$ASSUME_YES" = 1 ] && return 0
    if ( : < /dev/tty ) 2>/dev/null; then
        printf '%s [y/N] ' "$1" > /dev/tty
        read -r answer < /dev/tty || answer=n
        case $answer in y|Y|yes|YES) return 0 ;; *) return 1 ;; esac
    fi
    # No terminal (for example `curl | sh` from a script): the caller already
    # asked for exactly this, so proceed.
    return 0
}

# ---- Ed25519 verification ---------------------------------------------------
# The signature is checked by a small static verifier program, released as a
# signed asset of the release process. This script pins the verifier's SHA-256
# per platform (VERIFIER_SHA_* below) and runs it only after the downloaded
# bytes match that pin. The verifier is proven by a known-answer test (RFC 8032
# test vector 2, plus a corrupted signature that must fail) before it is used.
#
# Trust, stated plainly: this trusts (a) this script, which you fetched over
# HTTPS from yadori.link (its SHA-256 is published for the verify-first flow),
# and through it (b) the pinned verifier hash and (c) the pinned release keys.
# Nothing else needs to be trusted for the manifest signature check.

WORK=""
VERIFIER=""

# fetch_verifier: get the pinned verifier for $TARGET into $WORK (downloaded, or for
# --from taken from the directory next to the manifest file) and make it ready to
# run, or refuse. It only runs after its bytes match the pin.
fetch_verifier() {
    case $TARGET in
        macos-aarch64) pin=$VERIFIER_SHA_macos_aarch64 ;;
        linux-x86_64) pin=$VERIFIER_SHA_linux_x86_64 ;;
        *) pin="" ;;
    esac
    [ -z "$TEST_VERIFIER_SHA" ] || pin=$TEST_VERIFIER_SHA
    [ -n "$pin" ] || refuse 4 "this installer has no pinned Ed25519 verifier for $TARGET yet (the verifier release is not published). Nothing was installed."
    VERIFIER=$WORK/yadorilink-verify
    if [ -n "$FROM_FILE" ]; then
        [ -f "$FROM_DIR/yadorilink-verify-$TARGET" ] ||
            refuse 2 "--from needs the verifier program yadorilink-verify-$TARGET next to $FROM_FILE (release asset). Nothing was installed."
        cp "$FROM_DIR/yadorilink-verify-$TARGET" "$VERIFIER"
    else
        vurl=$VERIFIER_BASE/yadorilink-verify-$TARGET
        code=$(curl -sSL --max-redirs 5 --proto "$CURL_PROTO" --proto-redir "$CURL_PROTO" --tlsv1.2 --connect-timeout 15 --max-time 120 \
            --max-filesize 8388608 -o "$VERIFIER" -w '%{http_code}' "$vurl") ||
            refuse 3 "could not download the signature verifier ($vurl). Nothing was installed."
        [ "$code" = 200 ] || refuse 3 "could not download the signature verifier (HTTP $code from $vurl). Nothing was installed."
    fi
    [ "$(sha256_of "$VERIFIER")" = "$pin" ] || refuse 4 "the downloaded signature verifier does not match the SHA-256 pinned in this script. Refusing. Nothing was installed."
    chmod 700 "$VERIFIER"
    # RFC 8032 test vector 2.
    kat_pub=3d4017c3e843895a92b70aa74d1b7ebc9c982ccf2ec4968cc0cd55f12af4660c
    kat_sig=92a009a9f0d4cab8720e820b5f642540a2b27b5416503f8fb3762223ebdb69da085ac1e43e15996e458f3613d0f11d8c387b2eaeb4302aeeb00d291612bb0c00
    kat_bad=92a009a9f0d4cab8720e820b5f642540a2b27b5416503f8fb3762223ebdb69da085ac1e43e15996e458f3613d0f11d8c387b2eaeb4302aeeb00d291612bb0c01
    hex_to_file 72 "$WORK/kat.msg"
    hex_to_file "$kat_sig" "$WORK/kat.sig"
    hex_to_file "$kat_bad" "$WORK/kat.bad"
    if ! "$VERIFIER" "$kat_pub" "$WORK/kat.msg" "$WORK/kat.sig" >/dev/null 2>&1 ||
        "$VERIFIER" "$kat_pub" "$WORK/kat.msg" "$WORK/kat.bad" >/dev/null 2>&1; then
        refuse 4 "the signature verifier failed its self-test. Refusing. Nothing was installed."
    fi
}

