# state_dir: the data area the daemon uses (crates/yadorilink-fs-platform/src/state_dir.rs).
state_dir() {
    if [ -n "${YADORILINK_CONFIG_DIR:-}" ]; then printf '%s' "$YADORILINK_CONFIG_DIR"
