# envelope_field FILE KEY: the unescaped string value of KEY, exactly once.
envelope_field() {
    LC_ALL=C awk -v want="$2" '
    BEGIN { RS = "\001" }
    { s = $0 }
    END {
        # The optional top-level trust_chain array (key-rotation records) carries its own
        # nested key_id fields. The installer pins the trust set itself and ignores the
        # chain, so cut the array out before looking for a top-level field.
        tc = index(s, "\"trust_chain\"")
        if (want != "trust_chain" && tc > 0) {
            m = length(s); k = tc + 13
            while (k <= m && substr(s, k, 1) ~ /[ \t\r\n]/) k++
            if (substr(s, k, 1) != ":") exit 5
            k++
            while (k <= m && substr(s, k, 1) ~ /[ \t\r\n]/) k++
            if (substr(s, k, 1) != "[") exit 5
            depth = 0; instr = 0; e2 = 0
            for (; k <= m; k++) {
                ch = substr(s, k, 1)
                if (instr) { if (ch == "\\") k++; else if (ch == "\"") instr = 0; continue }
                if (ch == "\"") instr = 1
                else if (ch == "[") depth++
                else if (ch == "]") { depth--; if (depth == 0) { e2 = k; break } }
            }
            if (e2 == 0) exit 5
            s = substr(s, 1, tc - 1) substr(s, e2 + 1)
        }
        pat = "\"" want "\""
        first = index(s, pat)
        if (first == 0) exit 3
        rest = substr(s, first + length(pat))
        if (index(rest, pat) != 0) exit 4
        n = length(rest); i = 1
        while (i <= n && substr(rest, i, 1) ~ /[ \t\r\n]/) i++
        if (substr(rest, i, 1) != ":") exit 5
        i++
        while (i <= n && substr(rest, i, 1) ~ /[ \t\r\n]/) i++
        if (substr(rest, i, 1) != "\"") exit 5
        i++
        out = ""
        while (i <= n) {
            c = substr(rest, i, 1)
            if (c == "\"") { printf "%s", out; exit 0 }
            if (c == "\\") {
                i++; e = substr(rest, i, 1)
                if (e == "\"" || e == "\\" || e == "/") out = out e
                else if (e == "n") out = out "\n"
                else if (e == "t") out = out "\t"
                else if (e == "r") out = out "\r"
                else if (e == "u") {
                    h = substr(rest, i + 1, 4)
                    if (h !~ /^00[0-7][0-9a-fA-F]$/ || h == "0000") exit 6
                    v = 0
                    for (j = 3; j <= 4; j++) v = v * 16 + index("0123456789abcdef", tolower(substr(h, j, 1))) - 1
                    out = out sprintf("%c", v); i += 4
                } else exit 6
            } else out = out c
            i++
        }
        exit 7
    }' "$1"
}

# select_entry FILE CHANNEL PLATFORM ARCH [lenient]: print "OK" then key=value lines
# of the one release entry whose channel, platform, arch and install_source
# ("script": the engine bundle for script installs) match, plus the manifest's
# generated_at, expires_at and withdrawn_versions; otherwise an "ERR <reason>" line. In
# lenient mode a manifest without a matching entry still prints "OK" (with the
# entry fields empty): the live manifest of a channel is consulted for its
# withdrawals even when it has no entry for this platform.
select_entry() {
    LC_ALL=C awk -v ch="$2" -v pl="$3" -v ar="$4" -v lenient="${5:-}" '
    BEGIN { RS = "\001" }
    { body = $0 }
    function fail(m) { print "ERR " m; bad = 1; exit 0 }
    END {
        n = length(body); depth = 0; i = 1; key = ""; expectkey = 0; matches = 0; schema = ""; gen = ""; expv = ""; withdrawn = ""
        while (i <= n) {
            c = substr(body, i, 1)
            if (c ~ /[ \t\r\n,:]/) { i++; continue }
            if (c == "{") { depth++; expectkey = 0; if (depth == 3) { delete e } if (depth > 3) fail("unexpected nesting"); i++; continue }
            if (c == "[") { depth++; expectkey = 0; if (depth > 2) fail("unexpected nesting"); i++; continue }
            if (c == "}" || c == "]") {
                if (c == "}" && depth == 3) {
                    if (e["channel"] == ch && e["platform"] == pl && e["arch"] == ar && e["install_source"] == "script") {
                        matches++; for (k in e) sel[k] = e[k]
                    }
                }
                depth--; expectkey = 0; i++; continue
            }
            if (c == "\"") {
                j = i + 1; tok = ""
                while (j <= n && substr(body, j, 1) != "\"") {
                    if (substr(body, j, 1) == "\\") fail("escape in manifest field")
                    tok = tok substr(body, j, 1); j++
                }
                i = j + 1
            } else {
                j = i; tok = ""
                while (j <= n && substr(body, j, 1) !~ /[ \t\r\n,}\]]/) { tok = tok substr(body, j, 1); j++ }
                i = j
            }
            if (depth == 2 && key == "withdrawn_versions") { withdrawn = withdrawn (withdrawn == "" ? "" : " ") tok; continue }
            if (depth == 1 || depth == 3) {
                if (!expectkey) { key = tok; expectkey = 1 }
                else {
                    if (depth == 3) e[key] = tok
                    else if (key == "schema_version") schema = tok
                    else if (key == "generated_at") gen = tok
                    else if (key == "expires_at") expv = tok
                    expectkey = 0
                }
            }
        }
        if (bad) exit 0
        if (schema != "2") fail("unsupported manifest schema_version")
        if (matches == 0 && lenient == "") fail("no matching release")
        if (matches > 1) fail("ambiguous releases")
        print "OK"
        split("version minimum_supported_version kill_switch artifact_url artifact_sha256 artifact_size release_notes_url", names, " ")
        for (q = 1; q <= 7; q++) print names[q] "=" sel[names[q]]
        print "generated_at=" gen
        print "expires_at=" expv
        print "withdrawn_versions=" withdrawn
    }' "$1"
}

# semver_cmp A B: print -1, 0 or 1 (A relative to B).
semver_cmp() {
    awk -v a="$1" -v b="$2" '
    function core(v, out,   t) { sub(/^v/, "", v); sub(/\+.*/, "", v); split(v, t, "-"); split(t[1], out, "."); return substr(v, length(t[1]) + 2) }
    BEGIN {
        pa = core(a, ca); pb = core(b, cb)
        for (i = 1; i <= 3; i++) {
            if (ca[i] + 0 < cb[i] + 0) { print -1; exit }
            if (ca[i] + 0 > cb[i] + 0) { print 1; exit }
        }
        if (pa == pb) { print 0; exit }
        if (pa == "") { print 1; exit }
        if (pb == "") { print -1; exit }
        na = split(pa, xa, "."); nb = split(pb, xb, ".")
        for (i = 1; i <= (na > nb ? na : nb); i++) {
            if (i > na) { print -1; exit }
            if (i > nb) { print 1; exit }
            numa = xa[i] ~ /^[0-9]+$/; numb = xb[i] ~ /^[0-9]+$/
            if (numa && numb) { if (xa[i] + 0 != xb[i] + 0) { print (xa[i] + 0 < xb[i] + 0) ? -1 : 1; exit } }
            else if (numa) { print -1; exit }
            else if (numb) { print 1; exit }
            else if (xa[i] != xb[i]) { print (xa[i] < xb[i]) ? -1 : 1; exit }
        }
        print 0
    }'
}

# id_field FILE KEY: the value of KEY in engine-identity.json (written with
# one key per line); exactly one occurrence or failure.
id_field() {
    vals=$(sed -n "s/^ *\"$2\": *\"\\([^\"]*\\)\" *,\\{0,1\\} *\$/\\1/p; s/^ *\"$2\": *\\([0-9][0-9]*\\) *,\\{0,1\\} *\$/\\1/p" "$1")
    [ -n "$vals" ] || return 1
    [ "$(printf '%s\n' "$vals" | wc -l | tr -d ' ')" = 1 ] || return 1
    printf '%s' "$vals"
}

