$script:Ed25519Source = @'
using System;
using System.Numerics;
using System.Security.Cryptography;

// RFC 8032 section 6 reference algorithm: Ed25519 verification only.
public static class YadoriEd25519
{
    static readonly BigInteger P = BigInteger.Pow(2, 255) - 19;
    static readonly BigInteger L = BigInteger.Pow(2, 252) + BigInteger.Parse("27742317777372353535851937790883648493");
    static readonly BigInteger D = Mod(-121665 * Inv(121666));
    static readonly BigInteger I = BigInteger.ModPow(2, (P - 1) / 4, P);

    static BigInteger Mod(BigInteger a) { BigInteger r = a % P; return r.Sign < 0 ? r + P : r; }
    static BigInteger Inv(BigInteger a) { return BigInteger.ModPow(Mod(a), P - 2, P); }

    static BigInteger[] Add(BigInteger[] p, BigInteger[] q)
    {
        BigInteger a = Mod((p[1] - p[0]) * (q[1] - q[0]));
        BigInteger b = Mod((p[1] + p[0]) * (q[1] + q[0]));
        BigInteger c = Mod(p[3] * 2 * D * q[3]);
        BigInteger d = Mod(p[2] * 2 * q[2]);
        BigInteger e = b - a, f = d - c, g = d + c, h = b + a;
        return new BigInteger[] { Mod(e * f), Mod(g * h), Mod(f * g), Mod(e * h) };
    }

    static BigInteger[] Mul(BigInteger s, BigInteger[] p)
    {
        BigInteger[] q = new BigInteger[] { 0, 1, 1, 0 };
        for (int i = (int)(s.ToByteArray().Length * 8); i >= 0; i--)
        {
            q = Add(q, q);
            if (!((s >> i) & 1).IsZero) q = Add(q, p);
        }
        return q;
    }

    static bool Eq(BigInteger[] p, BigInteger[] q)
    {
        if (!Mod(p[0] * q[2] - q[0] * p[2]).IsZero) return false;
        if (!Mod(p[1] * q[2] - q[1] * p[2]).IsZero) return false;
        return true;
    }

    static BigInteger Le(byte[] b, int off, int len)
    {
        byte[] t = new byte[len + 1];
        Array.Copy(b, off, t, 0, len);
        return new BigInteger(t);
    }

    static BigInteger[] Decompress(byte[] raw, int off)
    {
        BigInteger y = Le(raw, off, 32);
        int sign = (int)((y >> 255) & 1);
        y = y & ((BigInteger.One << 255) - 1);
        if (y >= P) return null;
        BigInteger x2 = Mod((y * y - 1) * Inv(D * y * y + 1));
        BigInteger x;
        if (x2.IsZero)
        {
            if (sign != 0) return null;
            x = BigInteger.Zero;
        }
        else
        {
            x = BigInteger.ModPow(x2, (P + 3) / 8, P);
            if (!Mod(x * x - x2).IsZero) x = Mod(x * I);
            if (!Mod(x * x - x2).IsZero) return null;
            if ((int)(x & 1) != sign) x = P - x;
        }
        return new BigInteger[] { x, y, 1, Mod(x * y) };
    }

    public static bool Verify(byte[] pub, byte[] msg, byte[] sig)
    {
        if (pub == null || sig == null || msg == null || pub.Length != 32 || sig.Length != 64) return false;
        BigInteger[] A = Decompress(pub, 0);
        BigInteger[] R = Decompress(sig, 0);
        if (A == null || R == null) return false;
        BigInteger S = Le(sig, 32, 32);
        if (S >= L) return false;
        byte[] hin = new byte[64 + msg.Length];
        Array.Copy(sig, 0, hin, 0, 32);
        Array.Copy(pub, 0, hin, 32, 32);
        Array.Copy(msg, 0, hin, 64, msg.Length);
        byte[] h;
        using (SHA512 sha = SHA512.Create()) { h = sha.ComputeHash(hin); }
        BigInteger k = Le(h, 0, 64) % L;
        BigInteger gy = Mod(4 * Inv(5));
        byte[] by = new byte[32];
        byte[] gyb = gy.ToByteArray();
        Array.Copy(gyb, 0, by, 0, Math.Min(32, gyb.Length));
        BigInteger[] B = Decompress(by, 0);
        if (B == null) return false;
        return Eq(Mul(S, B), Add(R, Mul(k, A)));
    }
}
'@

function Fail([string]$Message) { throw ('yadorilink-install: error: ' + $Message) }
# Refuse CODE MESSAGE: fail with a specific exit status (see "Exit status" above).
function Refuse([int]$Code, [string]$Message) {
    $e = New-Object System.Exception ('yadorilink-install: error: ' + $Message)
    $e.Data['ExitCode'] = $Code
    throw $e
}

# One data area has one owner and only the owner's updater changes its programs
# (see the desktop and CLI coexistence design). The ownership record decides: no record means
# nothing is owned yet; the app, another installation or an unreadable record stops the install.
function Assert-NotManagedElsewhere {
    $dir = $env:YADORILINK_CONFIG_DIR
    if (-not $dir) { $dir = Join-Path $env:USERPROFILE '.yadorilink' }
    $rec = Join-Path $dir 'install-owner.json'
    if (-not (Test-Path -LiteralPath $rec)) { return }
    $record = $null
    try { $record = Get-Content -LiteralPath $rec -Raw | ConvertFrom-Json } catch { }
    if (-not $record -or -not $record.owner -or -not $record.install_source) {
        Refuse 19 "the ownership record $rec cannot be read, so who manages YadoriLink here is unknown. Nothing was installed. Fix or remove that file only if you know no other YadoriLink install uses this data."
    }
    if ($record.owner -eq 'gui') { Refuse 19 "YadoriLink is managed by the app ($($record.install_source)); the yadorilink command is already available from the app. Nothing was installed." }
    if ($record.install_source -ne 'script') { Refuse 19 "this machine's YadoriLink data belongs to another installation ($($record.install_source)), which has its own updater. Nothing was installed." }
}

function Show-Usage {
    $self = $null
    if ($PSCommandPath) { $self = $PSCommandPath }
    if ($self) {
        foreach ($line in (Get-Content -LiteralPath $self)) {
            if ($line -notmatch '^#') { break }
            if ($line -match '^#!') { continue }
            Write-Host ($line -replace '^# ?', '')
        }
    } else {
        Write-Host 'Usage: install.ps1 [-Prefix DIR] [-Channel beta|nightly] [-Version X.Y.Z] [-From FILE] [-NoModifyPath] [-Yes] [-Force] [-Uninstall]'
        Write-Host 'Full text: https://yadori.link/install.ps1'
    }
}

function ConvertFrom-Hex([string]$Hex) {
    if ($Hex.Length % 2 -ne 0 -or $Hex -notmatch '^[0-9a-fA-F]*$') { Fail 'internal error: bad hex' }
    $bytes = New-Object byte[] ($Hex.Length / 2)
    for ($i = 0; $i -lt $bytes.Length; $i++) { $bytes[$i] = [Convert]::ToByte($Hex.Substring(2 * $i, 2), 16) }
    , $bytes
}

function Get-Sha256([string]$Path) {
    $sha = [System.Security.Cryptography.SHA256]::Create()
    try {
        $stream = [System.IO.File]::OpenRead($Path)
        try { $hash = $sha.ComputeHash($stream) } finally { $stream.Dispose() }
    } finally { $sha.Dispose() }
    ([BitConverter]::ToString($hash) -replace '-', '').ToLowerInvariant()
}

