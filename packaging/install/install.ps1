# YadoriLink installer for Windows (x64), PowerShell 5.1 or newer.
#
#   irm https://yadori.link/install.ps1 | iex
#
# Options (when run as a file, or as a script block):
#   .\install.ps1 -Channel beta -Prefix D:\Tools\YadoriLink -NoModifyPath -Yes
#   & ([scriptblock]::Create((irm https://yadori.link/install.ps1))) -Channel nightly
# or through environment variables, which also work with `| iex`:
#   YADORILINK_CHANNEL, YADORILINK_VERSION, YADORILINK_PREFIX,
#   YADORILINK_NO_MODIFY_PATH=1, YADORILINK_YES=1
#
#   -Prefix DIR       install under DIR (default %LOCALAPPDATA%\YadoriLink; programs in DIR\bin)
#   -Channel NAME     beta (default) or nightly
#   -Version X.Y.Z    install exactly this version: the channel's current one,
#                     or an older one from its signed per-version manifest. Both
#                     are also checked against the live channel manifest, which
#                     can withdraw a version
#   -From FILE        offline install: FILE is a signed manifest envelope (a
#                     channel or per-version manifest); the engine zip sits next
#                     to it. If the live channel manifest is reachable it must
#                     not withdraw the version; if it is not, a loud warning says
#                     withdrawal was not checked
#   -NoModifyPath     do not add DIR\bin to your user PATH
#   -Yes              do not ask for confirmation
#   -Force            reinstall even if this version is already installed
#   -Uninstall        remove what this script installed
#   -Help             show this text
#
# What it does, in order, and nothing else:
#   1. Fetches the signed update manifest for the channel over HTTPS and
#      verifies its Ed25519 signature against the release key pinned below.
#      The check is done by an embedded C# reference implementation of
#      RFC 8032 (Windows PowerShell 5.1 has no Ed25519 in .NET).
#   2. Downloads the engine bundle the signed manifest names and checks its
#      size and SHA-256 against the manifest.
#   3. Unpacks it in a private staging directory and checks every file against
#      the SHA256SUMS inside the bundle, SHA256SUMS against engine-identity.json,
#      and the identity's channel, platform and source.
#   4. Only then points DIR\bin at the new version (a directory junction, no
#      administrator rights). The previous version stays on disk until the next
#      upgrade. Any failure before this step leaves an existing install alone.
# Exit status: 0 ok or already current, 1 other failure, 2 usage, 3 network,
# 4 signature, hash, replay or withdrawal refusal, 5 unsupported platform,
# 6 downgrade refused, 7 prefix not writable, 19 managed elsewhere (the app or a
# package manager owns this machine's YadoriLink data; nothing is installed).
# It never asks for elevation, never runs anything from the bundle before the
# checks pass (then only `yadorilink.exe --version`), and never starts the daemon.

