function Test-Semver([string]$Value) { $Value -match '^[0-9]+\.[0-9]+\.[0-9]+([-+][0-9A-Za-z.+-]+)?$' }

# Compare two semantic versions: -1, 0 or 1.
function Compare-Semver([string]$A, [string]$B) {
    $pa = $A.TrimStart('v') -split '\+', 2
    $pb = $B.TrimStart('v') -split '\+', 2
    $ca, $ra = ($pa[0] -split '-', 2)
    $cb, $rb = ($pb[0] -split '-', 2)
    $na = $ca -split '\.'; $nb = $cb -split '\.'
    for ($i = 0; $i -lt 3; $i++) {
        $x = [long]$na[$i]; $y = [long]$nb[$i]
        if ($x -lt $y) { return -1 }
        if ($x -gt $y) { return 1 }
    }
    if ($ra -eq $rb) { return 0 }
    if (-not $ra) { return 1 }
    if (-not $rb) { return -1 }
    $sa = $ra -split '\.'; $sb = $rb -split '\.'
    for ($i = 0; $i -lt [Math]::Max($sa.Length, $sb.Length); $i++) {
        if ($i -ge $sa.Length) { return -1 }
        if ($i -ge $sb.Length) { return 1 }
        $da = $sa[$i] -match '^[0-9]+$'; $db = $sb[$i] -match '^[0-9]+$'
        if ($da -and $db) {
            $x = [long]$sa[$i]; $y = [long]$sb[$i]
            if ($x -lt $y) { return -1 }
            if ($x -gt $y) { return 1 }
        } elseif ($da) { return -1 } elseif ($db) { return 1 } else {
            $c = [string]::CompareOrdinal($sa[$i], $sb[$i])
            if ($c -ne 0) { return [Math]::Sign($c) }
        }
    }
    0
}

# Download Url to Path. Returns the HTTP status, -1 for a transport failure
# (network down, timeout, connection closed early), or -2 when the response is
# unacceptable (too large, redirected to a non-HTTPS address); the reason for
# -2 is in $script:GetFileProblem.
function Get-File([string]$Url, [string]$Path, [long]$MaxBytes, [int]$TimeoutSec) {
    $script:GetFileProblem = $null
    try {
        [Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12
        $req = [Net.HttpWebRequest]::Create($Url)
        $req.Timeout = $TimeoutSec * 1000
        $req.ReadWriteTimeout = 60000
        $req.UserAgent = 'yadorilink-install.ps1'
        $req.AllowAutoRedirect = $true
        $req.MaximumAutomaticRedirections = 5
        try { $resp = $req.GetResponse() }
        catch [System.Net.WebException] {
            if ($_.Exception.Response) { return [int]$_.Exception.Response.StatusCode }
            return -1
        }
        try {
            if ($resp.ResponseUri.Scheme -ne 'https' -and -not $script:TestMode) { $script:GetFileProblem = "redirected to a non-HTTPS address ($($resp.ResponseUri))"; return -2 }
            if ($resp.ContentLength -gt $MaxBytes) { $script:GetFileProblem = "$Url is larger than expected"; return -2 }
            $in = $resp.GetResponseStream()
            $out = [System.IO.File]::Create($Path)
            try {
                $buf = New-Object byte[] 65536
                $total = 0L
                while (($n = $in.Read($buf, 0, $buf.Length)) -gt 0) {
                    $total += $n
                    if ($total -gt $MaxBytes) { $script:GetFileProblem = "$Url is larger than expected"; return -2 }
                    $out.Write($buf, 0, $n)
                }
                if ($resp.ContentLength -ge 0 -and $total -ne $resp.ContentLength) { return -1 }
            } finally { $out.Dispose(); $in.Dispose() }
            return [int]$resp.StatusCode
        } finally { $resp.Close() }
    } catch { return -1 }
}

# Get-Envelope URL PATH: download a signed envelope. Returns 'ok', 'notfound', 'http'
# (the status is in $script:HttpCode) or 'network'.
function Get-Envelope([string]$Url, [string]$Path) {
    if ($Url -notmatch '^https://' -and -not ($script:TestMode -and $Url -match '^http://')) { Refuse 4 'the manifest URL is not HTTPS' }
    $code = Get-File $Url $Path 1048576 60
    $script:HttpCode = $code
    if ($code -eq -2) { Refuse 4 "$($script:GetFileProblem). Refusing. Nothing was installed." }
    if ($code -eq -1) { return 'network' }
    if ($code -eq 200) { return 'ok' }
    if ($code -eq 404) { return 'notfound' }
    'http'
}

# Test-Envelope PATH: check the key id and the Ed25519 signature against the pinned trust set;
# returns the key id and the signed body text, or refuses (4).
function Test-Envelope([string]$Path) {
    $utf8 = New-Object System.Text.UTF8Encoding($false, $true)
    try {
        $envelope = $utf8.GetString([System.IO.File]::ReadAllBytes($Path)) | ConvertFrom-Json
        $envKey = [string]$envelope.key_id
        $manifestText = [string]$envelope.manifest_json
        $sig = [Convert]::FromBase64String([string]$envelope.signature_base64)
    } catch { Refuse 4 'the update manifest is malformed. Nothing was installed.' }
    if (-not $envKey -or -not $manifestText -or $sig.Length -ne 64) { Refuse 4 'the update manifest is malformed. Nothing was installed.' }
    $keyHex = $null
    foreach ($entry in $script:TrustSet) { if ($entry.Substring(0, $entry.IndexOf(':')) -eq $envKey) { $keyHex = $entry.Substring($entry.IndexOf(':') + 1) } }
    if (-not $keyHex) { Refuse 4 "update manifest is signed with key '$envKey', which is not one of the pinned release keys. Refusing. Nothing was installed." }
    if (-not [YadoriEd25519]::Verify((ConvertFrom-Hex $keyHex), $utf8.GetBytes($manifestText), $sig)) {
        Refuse 4 'the update manifest signature does NOT verify against the pinned release key. Refusing. Nothing was installed.'
    }
    [pscustomobject]@{ Key = $envKey; Text = $manifestText }
}

# Read-Manifest TEXT CHANNEL LENIENT: the facts of a verified body for this channel on
# windows-x86_64. Lenient mode accepts a manifest without a matching entry (the live manifest
# is consulted for its withdrawals even then).
function Read-Manifest([string]$Text, [string]$Channel, [bool]$Lenient) {
    $m = $Text | ConvertFrom-Json
    if ($m.schema_version -ne 2) { Refuse 4 'update manifest: unsupported manifest schema_version. Nothing was installed.' }
    $gm = [regex]::Match($Text, '"generated_at"\s*:\s*"([^"]*)"')
    $gen = if ($gm.Success) { $gm.Groups[1].Value } else { '' }
    if ($gen -notmatch '^[0-9]{4}-[0-9]{2}-[0-9]{2}T[0-9]{2}:[0-9]{2}:[0-9]{2}Z$') { Refuse 4 "update manifest has an invalid generated_at '$gen'. Nothing was installed." }
    $xm = [regex]::Match($Text, '"expires_at"\s*:\s*"([^"]*)"')
    $exp = if ($xm.Success) { $xm.Groups[1].Value } else { '' }
    $withdrawn = @()
    if ($m.PSObject.Properties['withdrawn_versions']) { $withdrawn = @($m.withdrawn_versions | ForEach-Object { [string]$_ }) }
    $found = @($m.releases | Where-Object { $_.channel -eq $Channel -and $_.platform -eq 'windows' -and $_.arch -eq 'x86_64' -and $_.install_source -eq 'script' })
    if ($found.Count -gt 1) { Refuse 4 "update manifest: ambiguous releases for $Channel/windows-x86_64. Nothing was installed." }
    if ($found.Count -eq 0 -and -not $Lenient) { Refuse 4 "update manifest: no matching release for $Channel/windows-x86_64. Nothing was installed." }
    $r = [ordered]@{ Gen = $gen; Expires = $exp; Withdrawn = $withdrawn; HasEntry = ($found.Count -eq 1); Version = ''; Kill = $false; Min = ''; Url = ''; Sha = ''; Size = 0L; Notes = '' }
    if ($found.Count -eq 1) {
        $e = $found[0]
        $r.Version = [string]$e.version; $r.Kill = ($e.kill_switch -eq $true); $r.Min = [string]$e.minimum_supported_version
        $r.Url = [string]$e.artifact_url; $r.Sha = [string]$e.artifact_sha256; $r.Size = [long]$e.artifact_size; $r.Notes = [string]$e.release_notes_url
    }
    [pscustomobject]$r
}

# Test-Entry R: shape checks on an entry read by Read-Manifest.
function Test-Entry($R) {
    if (-not (Test-Semver $R.Version)) { Refuse 4 "update manifest has an invalid version '$($R.Version)'" }
    if ($R.Sha -notmatch '^[0-9a-f]{64}$') { Refuse 4 'update manifest has an invalid SHA-256' }
    if ($R.Size -le 0) { Refuse 4 'update manifest has an invalid size' }
    if ($R.Url -notmatch '^https://[0-9A-Za-z./:_%+=~-]+$' -and -not ($script:TestMode -and $R.Url -match '^http://[0-9A-Za-z./:_%+=~-]+$')) { Refuse 4 'update manifest artifact URL is not HTTPS' }
}

# Assert-ReplayFloor GEN CHANNEL: the live manifest must not be older than this installer's floor.
function Assert-ReplayFloor([string]$Gen, [string]$Channel) {
    if ($script:MinManifestGeneratedAt -and [string]::CompareOrdinal($Gen, $script:MinManifestGeneratedAt) -lt 0) {
        Refuse 4 "the $Channel manifest was generated at $Gen, before $($script:MinManifestGeneratedAt), the oldest this installer accepts (a replayed old manifest?). Refusing. Nothing was installed."
    }
}

# Assert-NotExpired EXPIRES GEN CHANNEL: the live manifest must not be past its expires_at. Installers
# keep no state, so this is their only freshness control. It is required of the live channel
# manifest only: the per-version manifests (integrity facts for a pinned or offline install,
# published once and kept) never expire, so Read-Manifest does not look at expires_at and a
# snapshot with or without it is accepted.
function Assert-NotExpired([string]$Expires, [string]$Gen, [string]$Channel) {
    if ($Expires -notmatch '^[0-9]{4}-[0-9]{2}-[0-9]{2}T[0-9]{2}:[0-9]{2}:[0-9]{2}Z$') { Refuse 4 "update manifest has an invalid expires_at '$Expires'. Nothing was installed." }
    if ([string]::CompareOrdinal($Gen, $Expires) -ge 0) { Refuse 4 "update manifest expires_at $Expires is not after generated_at $Gen. Nothing was installed." }
    $now = if ($script:TestNow) { $script:TestNow } else { [DateTime]::UtcNow.ToString('yyyy-MM-ddTHH:mm:ssZ', [Globalization.CultureInfo]::InvariantCulture) }
    if ([string]::CompareOrdinal($Expires, $now) -lt 0) {
        Refuse 4 "the $Channel manifest expired at $Expires (it is $now now). Check that this computer's clock is correct, or try again later. Refusing. Nothing was installed."
    }
}

# Assert-LiveAllows LIVE VERSION CHANNEL: refuse a version the live channel manifest withdraws:
# listed as withdrawn, kill-switched, or below the channel's minimum supported version.
function Assert-LiveAllows($Live, [string]$Version, [string]$Channel) {
    if ($Live.Withdrawn -contains $Version) { Refuse 4 "version $Version has been withdrawn on the $Channel channel. Nothing was installed." }
    if ($Live.HasEntry -and $Live.Version -eq $Version -and $Live.Kill) { Refuse 4 "version $Version on the $Channel channel has been withdrawn (kill switch). Nothing was installed." }
    if ($Live.HasEntry -and $Live.Min -and (Compare-Semver $Version $Live.Min) -lt 0) { Refuse 4 "version $Version is below the minimum supported version $($Live.Min) of the $Channel channel. Nothing was installed." }
}

function Confirm-Action([string]$Prompt, [bool]$Yes) {
    if ($Yes) { return $true }
    try {
        if ([Environment]::UserInteractive -and -not [Console]::IsInputRedirected) {
            $a = Read-Host "$Prompt [y/N]"
            return ($a -match '^(y|yes)$')
        }
    } catch { }
    # No terminal: the caller asked for exactly this.
    $true
}

function Test-IsOurJunction([string]$Path, [string]$Root) {
    if (-not (Test-Path -LiteralPath $Path)) { return $false }
    $item = Get-Item -LiteralPath $Path -Force
    if (-not ($item.Attributes -band [IO.FileAttributes]::ReparsePoint)) { return $false }
    $target = [string]($item.Target | Select-Object -First 1)
    $target.StartsWith($Root.TrimEnd('\') + '\', [StringComparison]::OrdinalIgnoreCase)
}

function Remove-Junction([string]$Path) { [System.IO.Directory]::Delete($Path, $false) }

function Get-Receipt([string]$Path) {
    $r = @{}
    if (Test-Path -LiteralPath $Path) {
        foreach ($line in [System.IO.File]::ReadAllLines($Path)) {
            $i = $line.IndexOf('=')
            if ($i -gt 0) { $r[$line.Substring(0, $i)] = $line.Substring($i + 1) }
        }
    }
    $r
}

function Set-Receipt([string]$Path, [hashtable]$Values) {
    if ($script:TestFailReceipt) { throw 'injected receipt write failure' }
    $tmp = "$Path.new.$PID"
    $lines = foreach ($k in $Values.Keys | Sort-Object) { "$k=$($Values[$k])" }
    [System.IO.File]::WriteAllLines($tmp, [string[]]$lines)
    Move-Item -LiteralPath $tmp -Destination $Path -Force
}

function Get-UserPath { [Environment]::GetEnvironmentVariable('Path', 'User') }

function Add-UserPath([string]$Dir) {
    $cur = Get-UserPath
    $parts = @()
    if ($cur) { $parts = $cur -split ';' | Where-Object { $_ } }
    if ($parts -notcontains $Dir) {
        [Environment]::SetEnvironmentVariable('Path', ((@($parts) + $Dir) -join ';'), 'User')
    }
    if (($env:Path -split ';') -notcontains $Dir) { $env:Path = "$Dir;$env:Path" }
}

function Remove-UserPath([string]$Dir) {
    $cur = Get-UserPath
    if (-not $cur) { return }
    $parts = $cur -split ';' | Where-Object { $_ -and $_ -ne $Dir }
    [Environment]::SetEnvironmentVariable('Path', ($parts -join ';'), 'User')
}

# Files that were never downloaded to this PC (On-Demand placeholders) cannot be opened once
# YadoriLink is removed. Returns the warning lines, empty when the running daemon reports none.
# A daemon that does not answer leaves the count unknown, and unknown is not "none".
function Get-PlaceholderWarnings([string]$Bin) {
    $cli = Join-Path $Bin 'yadorilink.exe'
    $folders = $null
    if (Test-Path -LiteralPath $cli) {
        try {
            $raw = (& $cli status --json 2>$null | ForEach-Object { "$_" }) -join "`n"
            if ($LASTEXITCODE -eq 0) {
                $parsed = $raw | ConvertFrom-Json
                if ($null -ne $parsed.PSObject.Properties['folders']) { $folders = @($parsed.folders) }
            }
        } catch { $folders = $null }
    }
    if ($null -eq $folders) {
        return @('The daemon is not running, so YadoriLink cannot count files that were never downloaded to this computer (On-Demand placeholders). Such files cannot be opened here once YadoriLink is removed; they remain on your other devices. Start the daemon (yadorilink daemon start) to count them, or pass -Yes to continue.')
    }
    $lines = @()
    $unknown = @()
    $found = $false
    foreach ($f in $folders) {
        # An older daemon or CLI answers without these fields: absent or null is unknown, never zero.
        $c = $f.PSObject.Properties['placeholder_count']
        $o = $f.PSObject.Properties['on_demand']
        if ($null -eq $c -or $null -eq $c.Value -or $null -eq $o -or $null -eq $o.Value) {
            $unknown += "$($f.local_path)"
            continue
        }
        $n = 0
        if (-not [int64]::TryParse("$($c.Value)", [ref]$n)) { $unknown += "$($f.local_path)"; continue }
        if ($n -gt 0) {
            $found = $true
            $tag = ''
            if ($o.Value -eq $true) { $tag = ' (On-Demand folder)' }
            $lines += "$($f.local_path): $n file(s) were never downloaded to this computer$tag."
        }
    }
    foreach ($u in $unknown) {
        $lines += "${u}: this YadoriLink does not report how many files were never downloaded, so the count is unknown."
    }
    if ($found) {
        $lines += 'These files cannot be opened here once YadoriLink is removed; they remain on your other devices. Download the ones you need first, or pass -Yes to continue.'
    } elseif ($unknown.Count -gt 0) {
        $lines += 'Files that were never downloaded (On-Demand placeholders) cannot be opened here once YadoriLink is removed; they remain on your other devices. Pass -Yes to continue.'
    }
    $lines
}

function Invoke-Uninstall([string]$Prefix, [bool]$Yes) {
    $bin = Join-Path $Prefix 'bin'
    $receiptPath = Join-Path $Prefix 'install-receipt.txt'
    if (-not (Test-Path -LiteralPath $receiptPath)) {
        Write-Host "Nothing to uninstall: no YadoriLink install found under $Prefix."
        return
    }
    $warnings = @(Get-PlaceholderWarnings $bin)
    foreach ($w in $warnings) { Write-Host "WARNING: $w" }
    if ($warnings.Count -gt 0 -and -not $Yes) {
        # Losing unreadable files is confirmed on its own and never assumed when nobody can be asked.
        $asked = $false
        try {
            if ([Environment]::UserInteractive -and -not [Console]::IsInputRedirected) {
                $asked = ((Read-Host 'Remove YadoriLink anyway? [y/N]') -match '^(y|yes)$')
            }
        } catch { }
        if (-not $asked) { Fail 'nothing was removed; re-run with -Yes to continue' }
    }
    if (-not (Confirm-Action "Remove the YadoriLink install under ${Prefix}?" $Yes)) { Fail 'cancelled' }
    try { $lock = [System.IO.File]::Open((Join-Path $Prefix '.lock'), 'OpenOrCreate', 'ReadWrite', 'None') }
    catch { Fail 'another yadorilink install is running' }
    $receipt = Get-Receipt $receiptPath
    if (Test-IsOurJunction $bin $Prefix) { Remove-Junction $bin }
    if ($receipt['path_added'] -eq '1') { Remove-UserPath $bin }
    $versionsPath = Join-Path $Prefix 'versions'
    if (Test-Path -LiteralPath $versionsPath) { Remove-Item -LiteralPath $versionsPath -Recurse -Force -ErrorAction SilentlyContinue }
    if (Test-Path -LiteralPath $versionsPath) {
        # Files are still locked (usually the running daemon). Keep the receipt so the install stays managed and a retry works.
        $lock.Dispose()
        Fail "could not remove everything under $versionsPath (a file is in use, usually the running daemon). Stop it with 'yadorilink daemon stop' and run -Uninstall again. The install receipt was kept."
    }
    Remove-Item -LiteralPath $receiptPath -Force -ErrorAction SilentlyContinue
    Get-ChildItem -LiteralPath $Prefix -Force -Filter 'bin.old.*' -ErrorAction SilentlyContinue | ForEach-Object { Remove-Junction $_.FullName }
    $lock.Dispose()
    Remove-Item -LiteralPath (Join-Path $Prefix '.lock') -Force -ErrorAction SilentlyContinue
    if (-not (Get-ChildItem -LiteralPath $Prefix -Force -ErrorAction SilentlyContinue)) { Remove-Item -LiteralPath $Prefix -Force -ErrorAction SilentlyContinue }
    Write-Host 'Removed. Your sync data and sign-in are untouched; stop the daemon first with'
    Write-Host "'yadorilink daemon stop' if it is running, and remove its data directory yourself if you want it gone."
}

function Invoke-Install($Opt) {
    $channel = $Opt.Channel
    switch ($channel) {
        'beta' { $identityChannel = 'beta' }
        'nightly' { $identityChannel = 'dev' }
        default { Refuse 2 "unknown channel '$channel' (published channels: beta, nightly)" }
    }
    $wantVersion = ([string]$Opt.Version).TrimStart('v')

    if ($env:OS -ne 'Windows_NT') { Refuse 5 'this is the Windows installer. On macOS or Linux use: curl -fsSL https://yadori.link/install.sh | sh' }
    $arch = if ($script:TestArch) { $script:TestArch } elseif ($env:PROCESSOR_ARCHITEW6432) { $env:PROCESSOR_ARCHITEW6432 } else { $env:PROCESSOR_ARCHITECTURE }
    if ($arch -ne 'AMD64') { Refuse 5 "unsupported CPU '$arch'. YadoriLink engine bundles exist for macOS (Apple silicon), Linux (x86_64) and Windows (x86_64). Nothing was installed." }
    $target = 'windows-x86_64'
    Assert-NotManagedElsewhere

    $prefix = $Opt.Prefix
    if (-not $prefix) { $prefix = Join-Path $env:LOCALAPPDATA 'YadoriLink' }
    if (-not [System.IO.Path]::IsPathRooted($prefix)) { Refuse 2 '-Prefix must be an absolute path' }
    $prefix = [System.IO.Path]::GetFullPath($prefix).TrimEnd('\')
    $bin = Join-Path $prefix 'bin'
    $receiptPath = Join-Path $prefix 'install-receipt.txt'

    try { New-Item -ItemType Directory -Force -Path $prefix | Out-Null; $probe = Join-Path $prefix ".probe.$PID"; [System.IO.File]::WriteAllText($probe, 'x'); Remove-Item -LiteralPath $probe -Force }
    catch { Refuse 7 "cannot write to $prefix (read-only or no permission). Use -Prefix with a directory you own. Nothing was installed." }

    $lock = $null
    $stage = Join-Path $prefix ".staging.$PID"
    try {
        try { $lock = [System.IO.File]::Open((Join-Path $prefix '.lock'), 'OpenOrCreate', 'ReadWrite', 'None') }
        catch { Fail 'another yadorilink install is running' }
        if (Test-Path -LiteralPath $stage) { Remove-Item -LiteralPath $stage -Recurse -Force }
        New-Item -ItemType Directory -Path $stage | Out-Null
        $work = Join-Path $stage 'work'
        New-Item -ItemType Directory -Path $work | Out-Null

        Initialize-Verifier

        # 1. Signed manifests. The live channel manifest is always consulted: it is the only place
        # a withdrawal, a kill switch or a raised minimum can appear, so even a pinned version is
        # checked against it. Only an offline -From install may go on without it.
        $liveUrl = "$($script:ManifestBase)/$channel/manifest.json"
        $liveEnv = Join-Path $work 'envelope.json'
        $fromDir = $null
        if ($Opt.From) {
            $fromFile = [System.IO.Path]::GetFullPath([string]$Opt.From)
            if (-not (Test-Path -LiteralPath $fromFile -PathType Leaf)) { Refuse 2 "-From: $fromFile is not a file" }
            $fromDir = Split-Path -Parent $fromFile
            $v = Test-Envelope $fromFile
            Write-Host "Manifest signature verified (key $($v.Key), built-in Ed25519), offline install from $fromFile."
            $rel = Read-Manifest $v.Text $channel $false
            Test-Entry $rel
            if ($wantVersion -and $wantVersion -ne $rel.Version) { Refuse 4 "$fromFile is for version $($rel.Version), not $wantVersion. Nothing was installed." }
            if ($rel.Kill) { Refuse 4 "version $($rel.Version) in $fromFile is marked withdrawn (kill switch). Nothing was installed." }
            # The supplied manifest's own withdrawals and minimum apply even when the live one is unreachable.
            Assert-LiveAllows $rel $rel.Version $channel
            # The live manifest is checked when it can be reached; otherwise say so loudly.
            if ((Get-Envelope $liveUrl $liveEnv) -eq 'ok') {
                $lv = Test-Envelope $liveEnv
                $live = Read-Manifest $lv.Text $channel $true
                Assert-ReplayFloor $live.Gen $channel
                Assert-NotExpired $live.Expires $live.Gen $channel
                Assert-LiveAllows $live $rel.Version $channel
                Write-Host "The live $channel manifest does not withdraw $($rel.Version)."
            } else {
                [Console]::Error.WriteLine("yadorilink-install: error: WARNING: $liveUrl could not be reached (offline?), so it was NOT checked whether version $($rel.Version) has been withdrawn. Withdrawal not checked.")
            }
        } else {
            Write-Host "Checking $channel channel ($target)..."
            switch (Get-Envelope $liveUrl $liveEnv) {
                'ok' { }
                'notfound' {
                    Write-Host "No release is published yet on the $channel channel (no update manifest at $liveUrl)."
                    Write-Host 'Nothing was installed. Check https://yadori.link/ for the first release.'
                    $script:ExitCode = 1
                    return
                }
                'network' { Refuse 3 "could not reach $liveUrl. Check your network connection. Nothing was installed." }
                default { Refuse 3 "unexpected HTTP status $($script:HttpCode) from $liveUrl. Nothing was installed." }
            }
            $lv = Test-Envelope $liveEnv
            Write-Host "Manifest signature verified (key $($lv.Key), built-in Ed25519)."
            $live = Read-Manifest $lv.Text $channel $true
            Assert-ReplayFloor $live.Gen $channel
            Assert-NotExpired $live.Expires $live.Gen $channel
            if ($wantVersion -and $wantVersion -ne $live.Version) {
                # A pinned version: its signed per-version manifest proves integrity, the live
                # manifest decides whether it may still be installed.
                Assert-LiveAllows $live $wantVersion $channel
                $snapUrl = "$($script:ManifestBase)/$wantVersion/manifest.json"
                $snapEnv = Join-Path $work 'snapshot-envelope.json'
                switch (Get-Envelope $snapUrl $snapEnv) {
                    'ok' { }
                    'notfound' { Fail "version $wantVersion has no published manifest ($snapUrl). Nothing was installed." }
                    'network' { Refuse 3 "could not reach $snapUrl. Check your network connection. Nothing was installed." }
                    default { Refuse 3 "unexpected HTTP status $($script:HttpCode) from $snapUrl. Nothing was installed." }
                }
                $sv = Test-Envelope $snapEnv
                $rel = Read-Manifest $sv.Text $channel $false
                if ($rel.Version -ne $wantVersion) { Refuse 4 "the manifest for $wantVersion describes version $($rel.Version). Refusing. Nothing was installed." }
            } else {
                $rel = Read-Manifest $lv.Text $channel $false
            }
            Test-Entry $rel
            if ($rel.Kill) { Refuse 4 "version $($rel.Version) on the $channel channel has been withdrawn (kill switch). Nothing was installed." }
            Assert-LiveAllows $live $rel.Version $channel
        }
        $version = $rel.Version
        $url = $rel.Url
        $wantSha = $rel.Sha
        $wantSize = $rel.Size

        $receipt = Get-Receipt $receiptPath
        $installed = $receipt['version']
        if ($installed) {
            $cmp = Compare-Semver $version $installed
            if ($cmp -eq 0 -and $receipt['channel'] -eq $channel -and -not $Opt.Force) {
                Write-Host "YadoriLink $installed is already installed and up to date. (-Force reinstalls.)"
                if (-not $Opt.NoModifyPath -and -not ((Get-UserPath) -split ';' -contains $bin)) {
                    Add-UserPath $bin
                    $receipt['path_added'] = '1'
                    Set-Receipt $receiptPath $receipt
                    Write-Host "Added $bin to your user PATH. Open a new terminal to pick it up."
                }
                return
            }
            if ($cmp -lt 0) { Refuse 6 "installed version $installed is newer than $version on the $channel channel; not downgrading. Nothing was changed." }
        }
        if (Test-Path -LiteralPath $bin) {
            if (-not (Test-IsOurJunction $bin $prefix)) { Fail "$bin already exists and was not created by this script. Remove it or choose another -Prefix. Nothing was changed." }
        }
        $q = if ($installed) { "Upgrade YadoriLink $installed -> $version under ${prefix}?" } else { "Install YadoriLink $version under ${prefix}?" }
        if (-not (Confirm-Action $q $Opt.Yes)) { Fail 'cancelled' }

        # 2. Bundle download, checked against the signed manifest.
        $zipName = $url.Substring($url.LastIndexOf('/') + 1)
        $zip = Join-Path $stage $zipName
        if ($Opt.From) {
            $src = Join-Path $fromDir $zipName
            if (-not (Test-Path -LiteralPath $src -PathType Leaf)) { Refuse 2 "-From needs the engine bundle $zipName next to $fromFile. Nothing was installed." }
            Write-Host "Using $zipName ($version) from $fromDir..."
            Copy-Item -LiteralPath $src -Destination $zip
        } else {
            Write-Host "Downloading $zipName ($version)..."
            $code = Get-File $url $zip $wantSize 900
            if ($code -eq -2) { Refuse 4 "$($script:GetFileProblem). Refusing. Nothing was installed." }
            if ($code -eq -1) { Refuse 3 "download failed or was interrupted ($url). Nothing was installed." }
            if ($code -ne 200) { Refuse 3 "download failed (HTTP $code from $url). Nothing was installed." }
        }
        if ((Get-Item -LiteralPath $zip).Length -ne $wantSize) { Refuse 4 "downloaded bundle has the wrong size (expected $wantSize bytes). Refusing. Nothing was installed." }
        if ((Get-Sha256 $zip) -ne $wantSha) { Refuse 4 'downloaded bundle SHA-256 does not match the signed manifest. Refusing. Nothing was installed.' }

        # 3. Unpack privately (checking every name) and verify the contents.
        Add-Type -AssemblyName System.IO.Compression.FileSystem
        $extract = Join-Path $stage 'x'
        New-Item -ItemType Directory -Path $extract | Out-Null
        $extractRoot = [System.IO.Path]::GetFullPath($extract) + '\'
        try { $archive = [System.IO.Compression.ZipFile]::OpenRead($zip) } catch { Refuse 4 'bundle is not a valid zip. Nothing was installed.' }
        try {
            foreach ($entry in $archive.Entries) {
                $name = $entry.FullName
                if ($name.EndsWith('/')) { continue }
                if ($name -match '^[/\\]' -or $name -match '\\' -or $name -match ':' -or ($name -split '/') -contains '..') { Refuse 4 'bundle contains unsafe paths. Refusing. Nothing was installed.' }
                $dest = [System.IO.Path]::GetFullPath((Join-Path $extract ($name -replace '/', '\')))
                if (-not $dest.StartsWith($extractRoot, [StringComparison]::OrdinalIgnoreCase)) { Refuse 4 'bundle contains unsafe paths. Refusing. Nothing was installed.' }
                New-Item -ItemType Directory -Force -Path (Split-Path -Parent $dest) | Out-Null
                [System.IO.Compression.ZipFileExtensions]::ExtractToFile($entry, $dest, $false)
            }
        } finally { $archive.Dispose() }

        foreach ($f in 'SHA256SUMS', 'engine-identity.json', 'LICENSE', 'SOURCE.txt', 'THIRD-PARTY-LICENSES') {
            if (-not (Test-Path -LiteralPath (Join-Path $extract $f) -PathType Leaf)) { Refuse 4 "bundle is missing $f. Refusing. Nothing was installed." }
        }
        $listed = @{}
        foreach ($line in (Get-Content -LiteralPath (Join-Path $extract 'SHA256SUMS'))) {
            if (-not $line) { continue }
            if ($line -notmatch '^([0-9a-f]{64})  (.+)$') { Refuse 4 'SHA256SUMS is malformed. Refusing. Nothing was installed.' }
            $listed[$Matches[2]] = $Matches[1]
        }
        $actual = Get-ChildItem -LiteralPath $extract -Recurse -File | ForEach-Object { $_.FullName.Substring($extractRoot.Length) -replace '\\', '/' } | Where-Object { $_ -ne 'SHA256SUMS' -and $_ -ne 'engine-identity.json' }
        if (((@($actual) | Sort-Object) -join "`n") -ne ((@($listed.Keys) | Sort-Object) -join "`n")) { Refuse 4 "bundle contents differ from its SHA256SUMS. Refusing. Nothing was installed." }
        foreach ($p in $listed.Keys) {
            if ((Get-Sha256 (Join-Path $extract ($p -replace '/', '\'))) -ne $listed[$p]) { Refuse 4 "bundle file $p does not match SHA256SUMS. Refusing. Nothing was installed." }
        }

        $identity = [System.IO.File]::ReadAllText((Join-Path $extract 'engine-identity.json')) | ConvertFrom-Json
        if ((Get-Sha256 (Join-Path $extract 'SHA256SUMS')) -ne [string]$identity.bundle_sha256) { Refuse 4 "engine identity does not cover this bundle's SHA256SUMS. Refusing. Nothing was installed." }
        if ([string]$identity.channel -ne $identityChannel) { Refuse 4 "bundle is for channel '$($identity.channel)', expected '$identityChannel'. Refusing. Nothing was installed." }
        if ([string]$identity.public_commit_sha -notmatch '^[0-9a-f]{40}$') { Refuse 4 'engine identity has an invalid commit' }
        if ((Get-Content -LiteralPath (Join-Path $extract 'SOURCE.txt') -Raw) -notmatch [regex]::Escape([string]$identity.public_commit_sha)) { Refuse 4 "SOURCE.txt does not name the engine identity's source commit. Refusing. Nothing was installed." }
        if ([string]$identity.source.asset_name -ne $zipName) { Refuse 4 "engine identity names asset '$($identity.source.asset_name)' but '$zipName' was downloaded. Refusing. Nothing was installed." }
        if ($zipName -ne "yadorilink-engine-$($identity.channel)-$target.zip") { Refuse 4 "bundle '$zipName' is not the $target engine bundle for channel $($identity.channel). Refusing. Nothing was installed." }
        if ((Get-Sha256 (Join-Path $extract 'yadorilink-daemon.exe')) -ne [string]$identity.artifact_sha256) { Refuse 4 'daemon does not match the engine identity. Refusing. Nothing was installed.' }
        foreach ($name in 'yadorilink.exe', 'yadorilink-daemon.exe') {
            if (-not (Test-Path -LiteralPath (Join-Path $extract $name) -PathType Leaf)) { Refuse 4 "bundle lacks $name. Refusing. Nothing was installed." }
        }
        & (Join-Path $extract 'yadorilink.exe') --version *> $null
        if ($LASTEXITCODE -ne 0) { Fail 'the new yadorilink.exe does not run on this system (--version failed). Nothing was changed.' }

        # The daemon recognises a script install by this file beside its binaries
        # (crates/yadorilink-daemon/src/update/install_source.rs). It lives in the version
        # tree, so it follows the binaries and is removed with them. Written after
        # verification; failing to write it aborts before anything is switched.
        try { [System.IO.File]::WriteAllText((Join-Path $extract 'install-receipt.json'), ('{{"source":"script","version":"{0}","channel":"{1}"}}' -f $rel.Version, $channel) + "`n") }
        catch { Fail 'could not write the install receipt beside the binaries. Nothing was changed.' }

        # 4. Activate: move the verified tree into place, then repoint bin.
        $versionsDir = Join-Path $prefix 'versions'
        New-Item -ItemType Directory -Force -Path $versionsDir | Out-Null
        $stamp = [DateTimeOffset]::UtcNow.ToUnixTimeSeconds()
        $vdir = Join-Path $versionsDir "$version.$stamp.$PID"
        Move-Item -LiteralPath $extract -Destination $vdir

        $oldBin = $null
        if (Test-Path -LiteralPath $bin) {
            $oldBin = Join-Path $prefix "bin.old.$PID"
            [System.IO.Directory]::Move($bin, $oldBin)
        }
        try { New-Item -ItemType Junction -Path $bin -Target $vdir | Out-Null }
        catch {
            if ($oldBin) { [System.IO.Directory]::Move($oldBin, $bin) }
            Remove-Item -LiteralPath $vdir -Recurse -Force -ErrorAction SilentlyContinue
            Fail "could not point $bin at the new version. The previous install was restored."
        }
        $pathAdded = $receipt['path_added']
        $values = @{
            version = $version; dir = $vdir; previous_dir = $receipt['dir']; channel = $channel; target = $target
            engine_api_version = [string]$identity.engine_api_version; install_source = 'script'; path_added = $(if ($pathAdded) { $pathAdded } else { '0' })
        }
        # PATH and the receipt are committed together with the switch: if either
        # fails, the previous bin, version tree and PATH come back.
        $pathTouched = $false
        try {
            if (-not $Opt.NoModifyPath -and -not (($env:Path -split ';') -contains $bin) -and -not ((Get-UserPath) -split ';' -contains $bin)) {
                Add-UserPath $bin
                $pathTouched = $true
                $values['path_added'] = '1'
                $pathMsg = "Added $bin to your user PATH. Open a new terminal to pick it up."
            } elseif (-not (($env:Path -split ';') -contains $bin)) {
                $pathMsg = "$bin is not on your PATH. Add it, for example:`n  [Environment]::SetEnvironmentVariable('Path', `"$bin;`" + [Environment]::GetEnvironmentVariable('Path','User'), 'User')"
            }
            Set-Receipt $receiptPath $values
        } catch {
            if ($pathTouched) { Remove-UserPath $bin }
            Remove-Junction $bin
            if ($oldBin) { [System.IO.Directory]::Move($oldBin, $bin) }
            Remove-Item -LiteralPath $vdir -Recurse -Force -ErrorAction SilentlyContinue
            if (-not $receipt['dir']) { Remove-Item -LiteralPath $versionsDir -Force -ErrorAction SilentlyContinue }
            Fail "could not write the install receipt. The previous install was restored."
        }
        if ($oldBin) { Remove-Junction $oldBin }

        # Drop only the version tree the previous receipt recorded as "previous"
        # (it is now two generations old). Nothing else under versions\ is ours
        # to delete.
        $oldPrev = $receipt['previous_dir']
        if ($oldPrev -and $oldPrev -ne $vdir -and $oldPrev -ne $receipt['dir'] -and
            (Test-Path -LiteralPath $oldPrev -PathType Container) -and
            ((Split-Path -Parent $oldPrev) -eq $versionsDir)) {
            $item = Get-Item -LiteralPath $oldPrev -Force
            if (-not ($item.Attributes -band [IO.FileAttributes]::ReparsePoint)) {
                Remove-Item -LiteralPath $oldPrev -Recurse -Force -ErrorAction SilentlyContinue
            }
        }

        Write-Host ''
        Write-Host "Installed YadoriLink $version ($channel, $target) in $prefix."
        if ($rel.Notes) { Write-Host "Release notes: $($rel.Notes)" }
        if ($pathMsg) { Write-Host $pathMsg }
        Write-Host ''
        Write-Host 'Next steps:'
        Write-Host '  yadorilink daemon start'
        Write-Host '  yadorilink login'
        Write-Host 'Upgrade later by running the installer again. Remove with: install.ps1 -Uninstall'
    } finally {
        if ($lock) { $lock.Dispose() }
        if (Test-Path -LiteralPath $stage) { Remove-Item -LiteralPath $stage -Recurse -Force -ErrorAction SilentlyContinue }
        $lp = Join-Path $prefix '.lock'
        if (Test-Path -LiteralPath $lp) { Remove-Item -LiteralPath $lp -Force -ErrorAction SilentlyContinue }
    }
}

function Invoke-YadoriLinkInstall([string[]]$Arguments) {
    $script:ExitCode = 0
    $opt = @{
        Prefix = $env:YADORILINK_PREFIX; Channel = $(if ($env:YADORILINK_CHANNEL) { $env:YADORILINK_CHANNEL } else { 'beta' })
        Version = $env:YADORILINK_VERSION; NoModifyPath = ($env:YADORILINK_NO_MODIFY_PATH -eq '1'); Yes = ($env:YADORILINK_YES -eq '1')
        Force = $false; Uninstall = $false; From = $null
    }
    try {
        for ($i = 0; $i -lt $Arguments.Count; $i++) {
            switch -Regex ($Arguments[$i]) {
                '^-{1,2}(?i:prefix)$' { $i++; if ($i -ge $Arguments.Count) { Refuse 2 '-Prefix needs a directory' }; $opt.Prefix = $Arguments[$i] }
                '^-{1,2}(?i:channel)$' { $i++; if ($i -ge $Arguments.Count) { Refuse 2 '-Channel needs a name' }; $opt.Channel = $Arguments[$i] }
                '^-{1,2}(?i:version)$' { $i++; if ($i -ge $Arguments.Count) { Refuse 2 '-Version needs a value' }; $opt.Version = $Arguments[$i] }
                '^-{1,2}(?i:from)$' { $i++; if ($i -ge $Arguments.Count) { Refuse 2 '-From needs a file' }; $opt.From = $Arguments[$i] }
                '^-{1,2}(?i:nomodifypath)$' { $opt.NoModifyPath = $true }
                '^-{1,2}(?i:yes|y)$' { $opt.Yes = $true }
                '^-{1,2}(?i:force)$' { $opt.Force = $true }
                '^-{1,2}(?i:uninstall)$' { $opt.Uninstall = $true }
                '^-{1,2}(?i:help|h)$' { Show-Usage; return }
                default { Refuse 2 "unknown option: $($Arguments[$i]) (try -Help)" }
            }
        }
        if ($opt.Uninstall) {
            $prefix = $opt.Prefix
            if (-not $prefix) { $prefix = Join-Path $env:LOCALAPPDATA 'YadoriLink' }
            Invoke-Uninstall ([System.IO.Path]::GetFullPath($prefix).TrimEnd('\')) $opt.Yes
        } else {
            Invoke-Install $opt
        }
    } catch {
        [Console]::Error.WriteLine($_.Exception.Message)
        $script:ExitCode = 1
        if ($_.Exception.Data -and $_.Exception.Data.Contains('ExitCode')) { $script:ExitCode = [int]$_.Exception.Data['ExitCode'] }
    }
}

Invoke-YadoriLinkInstall $args
# A script file reports failure through its exit code. Under `| iex`, `exit`
# would close the user's PowerShell window, so only the error text is shown.
if ($PSCommandPath) { exit $script:ExitCode } else { $global:LASTEXITCODE = $script:ExitCode }
